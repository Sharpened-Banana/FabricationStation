local G = dofile("tools/gamedata/phase3_gen.lua")
local CSV = require("csv") -- 1a tools/lib/csv.lua

local FIX = "tests/fixtures/phase3/"
local function csv(n) local _, rows = CSV.read(FIX .. n); return rows end

local EMPTY_HEADER = "-- GENERATED by tools/gamedata/gen_phase3.lua --empty (wago.tools unavailable): Knowledge from "
  .. "hand-authored CSVs (unverified); RecipeSources not generated. Do not edit.\n"

describe("tools/gamedata/phase3_gen.lua", function()
  it("fixture quoted fields parse with 1a's csv", function()
    assert.equal("Herbalism trainer, Silvermoon", csv("knowledge_sources.csv")[2].hint)
  end)

  it("builds knowledge", function()
    local k = G.buildKnowledge(csv("skill_lines.csv"), csv("knowledge_sources.csv"))
    assert.same({ base = 164, name = "Blacksmithing" }, k.variants[2907])
    local bs = k.sources[1]
    assert.same({ "2907:weeklyQuest:93691", "weekly", { 93691 }, 263455, 2 }, { bs.id, bs.reset, bs.quests, bs.itemID, bs.points })
    assert.equal(1, k.sources[3].limit) -- order: 2907, 2909, 2912
    assert.is_nil(k.sources[2].limit)
  end)

  it("builds the full KnowledgeSource shape and no extra keys", function()
    local k = G.buildKnowledge(csv("skill_lines.csv"), csv("knowledge_sources.csv"))
    assert.equal(1, k.firstCraftPoints)
    assert.same({ [2907] = { base = 164, name = "Blacksmithing" }, [2909] = { base = 333, name = "Enchanting" },
      [2912] = { base = 182, name = "Herbalism" } }, k.variants)
    assert.same({ id = "2912:weeklyQuest:93700", skillLineID = 2912, category = "weeklyQuest", reset = "weekly",
      quests = { 93700, 93701, 93702, 93703, 93704 }, limit = 1, itemID = 263462, points = 3,
      hint = "Herbalism trainer, Silvermoon" }, k.sources[3])
    assert.same({ "2907:weeklyQuest:93691", "2909:drop:95048", "2912:weeklyQuest:93700" },
      { k.sources[1].id, k.sources[2].id, k.sources[3].id })
  end)

  it("maps every category to its reset and sorts by skillLineID, category, id", function()
    local rows = {}
    local cats = { "unique", "darkmoon", "drop", "treasure", "treatise", "weeklyQuest" }
    for i, c in ipairs(cats) do rows[#rows + 1] = { skillLineID = "2907", category = c, quests = tostring(100 + i), points = "1" } end
    rows[#rows + 1] = { skillLineID = "2907", category = "treasure", quests = "50 51", points = "1" }
    rows[#rows + 1] = { skillLineID = "2909", category = "drop", quests = "1", points = "1", hint = "" }
    local k = G.buildKnowledge(csv("skill_lines.csv"), rows)
    local got = {}
    for _, s in ipairs(k.sources) do got[#got + 1] = s.id .. "=" .. s.reset end
    assert.same({ "2907:darkmoon:102=monthly", "2907:drop:103=weekly", "2907:treasure:104=weekly",
      "2907:treasure:50=weekly", "2907:treatise:105=weekly", "2907:unique:101=once", "2907:weeklyQuest:106=weekly",
      "2909:drop:1=weekly" }, got)
    assert.is_nil(k.sources[8].hint) -- empty optional columns become nil
    assert.is_nil(k.sources[8].itemID)
  end)

  it("rejects bad rows with row numbers", function()
    assert.has_error(function() G.buildKnowledge(csv("skill_lines.csv"),
      { { skillLineID = "2907", category = "foo", quests = "1", points = "1" } }) end, "row 1: unknown category 'foo'")
    assert.has_error(function() G.buildKnowledge(csv("skill_lines.csv"),
      { { skillLineID = "9999", category = "unique", quests = "1", points = "1" } }) end, "row 1: unknown skillLineID 9999")
    assert.has_error(function() G.buildKnowledge(csv("skill_lines.csv"),
      { { skillLineID = "2907", category = "unique", quests = "", points = "1" } }) end, "row 1: no quests")
  end)

  it("rejects bad numbers, duplicate ids and bad skill lines", function()
    local function bad(row, msg)
      local good = { skillLineID = "2909", category = "drop", quests = "1", points = "1" }
      assert.has_error(function() G.buildKnowledge(csv("skill_lines.csv"), { good, row }) end, msg)
    end
    bad({ skillLineID = "2907", category = "unique", quests = "1 x", points = "1" }, "row 2: bad quest ID 'x'")
    bad({ skillLineID = "2907", category = "unique", quests = "1", points = "0" }, "row 2: bad points '0'")
    bad({ skillLineID = "2907", category = "unique", quests = "1", points = "" }, "row 2: bad points ''")
    bad({ skillLineID = "2907", category = "unique", quests = "1", points = "1", limit = "0" }, "row 2: bad limit '0'")
    bad({ skillLineID = "2907", category = "unique", quests = "1", points = "1", itemID = "1.5" }, "row 2: bad itemID '1.5'")
    bad({ skillLineID = "2909", category = "drop", quests = "1 2", points = "1" }, "row 2: duplicate id 2909:drop:1")
    assert.has_error(function() G.buildKnowledge({ { skillLineID = "2907", base = "", name = "X" } }, {}) end,
      "skill_lines row 1: bad base ''")
    assert.has_error(function() G.buildKnowledge({ { skillLineID = "2907", base = "164", name = "" } }, {}) end,
      "skill_lines row 1: no name")
    assert.has_error(function() G.buildKnowledge({ { skillLineID = "2907", base = "164", name = "A" },
      { skillLineID = "2907", base = "164", name = "B" } }, {}) end, "skill_lines row 2: duplicate skillLineID 2907")
  end)

  it("builds recipe sources", function()
    local s = G.buildRecipeSources(csv("skill_lines.csv"), csv("SkillLineAbility.csv"), csv("SpellEffect.csv"),
      csv("ItemEffect.csv"), csv("ItemXItemEffect.csv"))
    assert.same({ kind = "auto" }, s.bySkillLine[2907][5001])
    assert.same({ kind = "item", itemID = 8002 }, s.bySkillLine[2907][5002])
    assert.same({ kind = "unknown" }, s.bySkillLine[2907][5003])
    assert.is_nil(s.bySkillLine[171])
  end)

  it("files recipes under SkillupSkillLineID, as real exports do (SkillLine is the base profession)", function()
    local sla = { { SkillLine = "164", SkillupSkillLineID = "2907", Spell = "5101", AcquireMethod = "1" },
                  { SkillLine = "2907", SkillupSkillLineID = "0", Spell = "5102", AcquireMethod = "1" },
                  { SkillLine = "164", SkillupSkillLineID = "0", Spell = "5103", AcquireMethod = "1" } }
    local s = G.buildRecipeSources(csv("skill_lines.csv"), sla, {}, {}, {})
    assert.same({ [5101] = { kind = "auto" }, [5102] = { kind = "auto" } }, s.bySkillLine[2907])
  end)

  it("finds recipe items whose ItemEffect learns the recipe spell directly (TriggerType 6)", function()
    local sla = { { SkillLine = "164", SkillupSkillLineID = "2907", Spell = "5201", AcquireMethod = "0" },
                  { SkillLine = "164", SkillupSkillLineID = "2907", Spell = "5202", AcquireMethod = "0" } }
    local ie = { { ID = "60", SpellID = "5201", TriggerType = "6" }, { ID = "61", SpellID = "5201", TriggerType = "6" },
                 { ID = "62", SpellID = "5202", TriggerType = "0" } }
    local ix = { { ItemEffectID = "60", ItemID = "9300" }, { ItemEffectID = "61", ItemID = "9250" }, { ItemEffectID = "62", ItemID = "9400" } }
    local s = G.buildRecipeSources(csv("skill_lines.csv"), sla, {}, ie, ix)
    assert.same({ kind = "item", itemID = 9250 }, s.bySkillLine[2907][5201])
    assert.same({ kind = "unknown" }, s.bySkillLine[2907][5202])
  end)

  it("lets the lowest teaching itemID win and ignores non-learn effects", function()
    local se = csv("SpellEffect.csv")
    se[#se + 1] = { ID = "3", Effect = "36", ["EffectMiscValue[0]"] = "0", ["EffectMiscValue[1]"] = "0", EffectTriggerSpell = "5003", SpellID = "7003" }
    se[#se + 1] = { ID = "4", Effect = "36", ["EffectMiscValue[0]"] = "0", ["EffectMiscValue[1]"] = "0", EffectTriggerSpell = "5003", SpellID = "7004" }
    se[#se + 1] = { ID = "5", Effect = "6", ["EffectMiscValue[0]"] = "0", ["EffectMiscValue[1]"] = "0", EffectTriggerSpell = "5001", SpellID = "7004" }
    local ie = { { ID = "50", SpellID = "7003" }, { ID = "51", SpellID = "7004" } }
    local ix = { { ItemEffectID = "50", ItemID = "9100" }, { ItemEffectID = "51", ItemID = "9050" }, { ItemEffectID = "50", ItemID = "9200" } }
    local s = G.buildRecipeSources(csv("skill_lines.csv"), csv("SkillLineAbility.csv"), se, ie, ix)
    assert.same({ kind = "item", itemID = 9050 }, s.bySkillLine[2907][5003])
    assert.same({ kind = "auto" }, s.bySkillLine[2907][5001])
  end)

  it("reads array columns in the _0 header style too", function()
    local se = { { ID = "2", Effect = "16", EffectMiscValue_0 = "93691", EffectTriggerSpell = "0", SpellID = "7100" } }
    local k = G.buildKnowledge(csv("skill_lines.csv"), csv("knowledge_sources.csv"))
    k.sources[1].quests = { 11111 }
    assert.same({ "2907:weeklyQuest:93691: item 263455 completes quest 93691, table has 11111" },
      G.crossCheck(k, se, csv("ItemEffect.csv"), csv("ItemXItemEffect.csv")))
  end)

  it("names the table and column when a DB2 value is not a number", function()
    local sla = { { SkillLine = "2907", Spell = "abc", AcquireMethod = "0" } }
    assert.has_error(function() G.buildRecipeSources(csv("skill_lines.csv"), sla, {}, {}, {}) end,
      "SkillLineAbility row 1: Spell is not a number: 'abc'")
  end)

  it("cross-checks quest IDs from item spells", function()
    local k = G.buildKnowledge(csv("skill_lines.csv"), csv("knowledge_sources.csv"))
    k.sources[1].quests = { 11111 }
    assert.same({ "2907:weeklyQuest:93691: item 263455 completes quest 93691, table has 11111" },
      G.crossCheck(k, csv("SpellEffect.csv"), csv("ItemEffect.csv"), csv("ItemXItemEffect.csv")))
  end)

  it("cross-check passes on matching fixtures", function()
    local k = G.buildKnowledge(csv("skill_lines.csv"), csv("knowledge_sources.csv"))
    assert.same({}, G.crossCheck(k, csv("SpellEffect.csv"), csv("ItemEffect.csv"), csv("ItemXItemEffect.csv")))
  end)

  it("renders 1a's data-file format deterministically and loads via GameData.Define", function()
    local k = G.buildKnowledge(csv("skill_lines.csv"), csv("knowledge_sources.csv"))
    local src = G.render("Knowledge", "12.1.5", 70575, k)
    assert.equal(src, G.render("Knowledge", "12.1.5", 70575, k))
    assert.truthy(src:find("^%-%- GENERATED by tools/gamedata/gen_phase3.lua from wago.tools DB2 CSV, build 12.1.5.70575. Do not edit.\n", 1))
    local ns = load_files({}, { "Data/GameData.lua" }); loadstring(src)("FabricationStation", ns)
    assert.equal(2, ns.GameData.Get("Knowledge").sources[1].points)
    assert.is_false(ns.GameData.Status(70575).missing)
  end)

  it("renders the 1a layout: header, ADDON_NAME line, one Define; nil build and the --empty header", function()
    local src = G.render("RecipeSources", "12.1.5", nil, { bySkillLine = {} }, { empty = true })
    assert.equal(EMPTY_HEADER .. "local ADDON_NAME, ns = ...\n"
      .. 'ns.GameData.Define("RecipeSources", nil, {\n\tbySkillLine = {},\n})\n', src)
    local ns = load_files({}, { "Data/GameData.lua" }); loadstring(src)("FabricationStation", ns)
    assert.same({ bySkillLine = {} }, ns.GameData.Get("RecipeSources"))
    assert.is_true(ns.GameData.Status(70575).missing)
  end)
end)

describe("tools/gamedata/gen_phase3.lua", function()
  local created = {}
  after_each(function()
    for _, d in ipairs(created) do os.execute("rm -rf '" .. d .. "'") end
    created = {}
  end)

  local function tmpdir()
    local d = os.tmpname(); os.remove(d); os.execute("mkdir -p " .. d)
    created[#created + 1] = d
    return d
  end
  local function slurp(path)
    local f = assert(io.open(path, "rb")); local s = f:read("*a"); f:close(); return s
  end
  local function spit(path, text)
    local f = assert(io.open(path, "wb")); f:write(text); f:close()
  end
  local function gen(args, dir)
    local code = run_cmd("lua tools/gamedata/gen_phase3.lua " .. args .. " >" .. dir .. "/stdout 2>" .. dir .. "/stderr")
    return code, slurp(dir .. "/stdout"), slurp(dir .. "/stderr")
  end
  local function exists(path)
    local f = io.open(path, "r"); if f then f:close() end; return f ~= nil
  end
  local function load_out(out)
    return load_files({}, { "Data/GameData.lua", out .. "/GameData_Knowledge.lua", out .. "/GameData_RecipeSources.lua" })
  end
  -- A sources dir whose Blacksmithing row names the wrong quest (cross-check warning).
  local function bad_sources()
    local d = tmpdir()
    os.execute("cp " .. FIX .. "skill_lines.csv " .. d)
    spit(d .. "/knowledge_sources.csv", (slurp(FIX .. "knowledge_sources.csv"):gsub("2907,weeklyQuest,93691,", "2907,weeklyQuest,11111,")))
    return d
  end
  local ARGS = "--build 12.1.5.70575 --cache " .. FIX .. " --sources " .. FIX .. " --out "

  it("writes both build-stamped files from the cache and sources", function()
    local out = tmpdir()
    local code, stdout, stderr = gen(ARGS .. out, out)
    assert.equal(0, code, stderr)
    assert.truthy(stdout:find("wrote 2 GameData files for build 12.1.5.70575 to " .. out, 1, true), stdout)
    for _, f in ipairs({ "GameData_Knowledge.lua", "GameData_RecipeSources.lua" }) do
      local header = "-- GENERATED by tools/gamedata/gen_phase3.lua from wago.tools DB2 CSV, build 12.1.5.70575. Do not edit.\n"
        .. "local ADDON_NAME, ns = ...\n"
      assert.equal(header, slurp(out .. "/" .. f):sub(1, #header))
    end
    local ns = load_out(out)
    assert.same(G.buildKnowledge(csv("skill_lines.csv"), csv("knowledge_sources.csv")), ns.GameData.Get("Knowledge"))
    assert.same({ [5001] = { kind = "auto" }, [5002] = { kind = "item", itemID = 8002 }, [5003] = { kind = "unknown" } },
      ns.GameData.Get("RecipeSources").bySkillLine[2907])
    assert.equal(70575, ns.GameData.Build())
    assert.is_false(ns.GameData.Status(70575).missing)
  end)

  it("is deterministic", function()
    local a, b = tmpdir(), tmpdir()
    gen(ARGS .. a, a); gen(ARGS .. b, b)
    for _, f in ipairs({ "GameData_Knowledge.lua", "GameData_RecipeSources.lua" }) do
      assert.equal(slurp(a .. "/" .. f), slurp(b .. "/" .. f))
    end
  end)

  it("prints cross-check warnings and exits 1 without writing, unless --allow-warnings", function()
    local src, out = bad_sources(), tmpdir()
    local args = "--build 12.1.5.70575 --cache " .. FIX .. " --sources " .. src .. " --out " .. out
    local code, _, stderr = gen(args, out)
    assert.equal(1, code)
    assert.truthy(stderr:find("2907:weeklyQuest:11111: item 263455 completes quest 93691, table has 11111", 1, true), stderr)
    assert.truthy(stderr:find("--allow-warnings", 1, true), stderr)
    assert.is_false(exists(out .. "/GameData_Knowledge.lua"))
    assert.is_false(exists(out .. "/GameData_RecipeSources.lua"))

    code, _, stderr = gen(args .. " --allow-warnings", out)
    assert.equal(0, code, stderr)
    assert.truthy(stderr:find("completes quest 93691", 1, true), stderr)
    assert.equal(11111, load_out(out).GameData.Get("Knowledge").sources[1].quests[1])
  end)

  it("--empty writes Knowledge from the CSVs, an ungenerated RecipeSources, and skips the cache and cross-check", function()
    local src, out = bad_sources(), tmpdir()
    local code, _, stderr = gen("--empty --build 12.1.5.70575 --sources " .. src .. " --out " .. out, out)
    assert.equal(0, code, stderr)
    assert.equal("", stderr)
    local k, r = slurp(out .. "/GameData_Knowledge.lua"), slurp(out .. "/GameData_RecipeSources.lua")
    local head = EMPTY_HEADER .. "local ADDON_NAME, ns = ...\n"
    assert.equal(head, k:sub(1, #head))
    assert.truthy(k:find('\nns%.GameData%.Define%("Knowledge", 70575, {\n'))
    assert.equal(EMPTY_HEADER .. "local ADDON_NAME, ns = ...\n"
      .. 'ns.GameData.Define("RecipeSources", nil, {\n\tbySkillLine = {},\n})\n', r)
    local ns = load_out(out)
    assert.equal(3, #ns.GameData.Get("Knowledge").sources)
    assert.same({ bySkillLine = {} }, ns.GameData.Get("RecipeSources"))
    assert.is_true(ns.GameData.Status(70575).missing)
  end)

  it("names a missing cache CSV and how to fetch it", function()
    local cache, out = tmpdir(), tmpdir()
    os.execute("cp " .. FIX .. "*.csv " .. cache)
    os.remove(cache .. "/ItemXItemEffect.csv")
    local code, _, stderr = gen("--build 12.1.5.70575 --cache " .. cache .. " --sources " .. FIX .. " --out " .. out, out)
    assert.equal(1, code)
    assert.truthy(stderr:find("ItemXItemEffect.csv", 1, true), stderr)
    assert.truthy(stderr:find("fetch.sh 12.1.5.70575", 1, true), stderr)
  end)

  it("names the source file and row of a bad knowledge row", function()
    local src, out = tmpdir(), tmpdir()
    os.execute("cp " .. FIX .. "skill_lines.csv " .. src)
    spit(src .. "/knowledge_sources.csv", "skillLineID,category,quests,limit,itemID,points,hint,credit\n2907,foo,1,,,1,,x\n")
    local code, _, stderr = gen("--empty --build 12.1.5.70575 --sources " .. src .. " --out " .. out, out)
    assert.equal(1, code)
    assert.truthy(stderr:find("knowledge_sources.csv", 1, true), stderr)
    assert.truthy(stderr:find("row 1: unknown category 'foo'", 1, true), stderr)
    assert.is_false(exists(out .. "/GameData_Knowledge.lua"))
  end)

  it("rejects missing or malformed arguments", function()
    local d = tmpdir()
    local code, _, stderr = gen("--build 12.1.5.70575 --cache " .. FIX, d)
    assert.equal(1, code); assert.truthy(stderr:find("--out", 1, true), stderr)
    code, _, stderr = gen("--build 70575 --cache " .. FIX .. " --out " .. d, d)
    assert.equal(1, code); assert.truthy(stderr:find("--build must look like", 1, true), stderr)
    code, _, stderr = gen("--empty --out " .. d, d)
    assert.equal(1, code); assert.truthy(stderr:find("--build", 1, true), stderr)
    code, _, stderr = gen("--build 12.1.5.70575 --out " .. d, d)
    assert.equal(1, code); assert.truthy(stderr:find("--cache", 1, true), stderr)
    code, _, stderr = gen("--bogus", d)
    assert.equal(1, code); assert.truthy(stderr:find("unknown argument --bogus", 1, true), stderr)
  end)
end)
