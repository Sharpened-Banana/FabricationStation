local csv = require("csv")

describe("csv", function()
  it("parses quoted commas and doubled quotes", function()
    local h, rows = csv.parse('ID,Name\n1,"a,b"\n2,"say ""hi"""\n')
    assert.same({ "ID", "Name" }, h); assert.equals("a,b", rows[1].Name); assert.equals('say "hi"', rows[2].Name); assert.equals(2, #rows)
  end)
  it("parses multi-line quoted fields and CRLF", function()
    local _, rows = csv.parse('ID,D\r\n1,"l1\nl2"\r\n'); assert.equals("l1\nl2", rows[1].D)
  end)
  it("reads array columns in either style", function()
    assert.equals("5", csv.col({ ["Pos[0]"] = "5" }, "Pos", 0)); assert.equals("6", csv.col({ Pos_1 = "6" }, "Pos", 1))
  end)
  it("names available columns when one is missing", function()
    assert.has_error(function() csv.col({ ID = "1" }, "ItemID") end, "missing column ItemID; have: ID")
  end)
  it("lists available columns sorted", function()
    assert.has_error(function() csv.col({ b = "1", a = "2" }, "c") end, "missing column c; have: a, b")
  end)
  it("reads plain columns and empty values", function()
    assert.equals("7", csv.col({ ID = "7" }, "ID")); assert.equals("", csv.col({ ID = "" }, "ID"))
  end)
  it("handles a file without a trailing newline and empty fields", function()
    local h, rows = csv.parse("A,B,C\n1,,3")
    assert.same({ "A", "B", "C" }, h); assert.equals(1, #rows)
    assert.same({ A = "1", B = "", C = "3" }, rows[1])
  end)
  it("returns no rows for a header-only file", function()
    local h, rows = csv.parse("A,B\n"); assert.same({ "A", "B" }, h); assert.same({}, rows)
  end)
  it("skips blank lines", function()
    local _, rows = csv.parse("A\n1\n\n2\n"); assert.equals(2, #rows)
  end)
  it("strips a UTF-8 BOM", function()
    local h = csv.parse("\239\187\191ID,Name\n"); assert.same({ "ID", "Name" }, h)
  end)
  it("keeps quoted empty and CR-only content inside quotes", function()
    local _, rows = csv.parse('A,B\n"","x\r\ny"\n'); assert.equals("", rows[1].A); assert.equals("x\r\ny", rows[1].B)
  end)
  it("errors on an unterminated quote or a wrong field count", function()
    assert.has_error(function() csv.parse('A\n"abc\n') end)
    assert.has_error(function() csv.parse("A,B\n1\n") end)
    assert.has_error(function() csv.parse("A,B\n1,2,3\n") end)
  end)
  it("reads a file", function()
    local path = os.tmpname()
    local f = assert(io.open(path, "wb")); f:write("ID,Name\n1,x\n"); f:close()
    local h, rows = csv.read(path); os.remove(path)
    assert.same({ "ID", "Name" }, h); assert.equals("x", rows[1].Name)
  end)
  it("errors when the file cannot be opened", function()
    assert.has_error(function() csv.read("/nonexistent/file.csv") end)
  end)
end)
