local FIXTURES = "tests/fixtures/gamedata/12.1.5.70575"
local GENERATED = { "GameData_Professions.lua", "GameData_Reagents.lua", "GameData_Difficulty.lua", "GameData_Spec.lua" }
local DEFINES = { "ProfessionLines", "ReagentQuality", "ReagentCategories", "OptionalReagents", "CraftingData", "ItemCraftingData",
  "QualityThresholds", "ConcentrationCurves", "SpecEntryEffects", "RecipeLabels" }

local function tmpdir()
  local d = os.tmpname(); os.remove(d); os.execute("mkdir -p " .. d)
  return d
end

local function slurp(path)
  local f = assert(io.open(path, "rb")); local s = f:read("*a"); f:close(); return s
end

local function spit(path, text)
  local f = assert(io.open(path, "wb")); f:write(text); f:close()
end

local function generate(args, dir)
  local code = run_cmd("lua tools/gamedata/generate.lua " .. args .. " >" .. dir .. "/stdout 2>" .. dir .. "/stderr")
  return code, slurp(dir .. "/stdout"), slurp(dir .. "/stderr")
end

local function load_generated(out)
  local paths = { "Data/GameData.lua" }
  for _, f in ipairs(GENERATED) do paths[#paths + 1] = out .. "/" .. f end
  return load_files({}, paths)
end

-- A copy of the fixture cache the test can corrupt.
local function fixture_copy()
  local d = tmpdir(); os.execute("cp " .. FIXTURES .. "/*.csv " .. d)
  return d
end

describe("tools/gamedata/generate.lua", function()
  it("generates loadable, build-stamped data files from cached CSVs", function()
    local out = os.tmpname(); os.remove(out); os.execute("mkdir -p " .. out)
    assert.equals(0, run_cmd("lua tools/gamedata/generate.lua --build 12.1.5.70575 --cache tests/fixtures/gamedata/12.1.5.70575 --out " .. out .. " >/dev/null"))
    local ns = load_files({}, { "Data/GameData.lua", out .. "/GameData_Reagents.lua", out .. "/GameData_Difficulty.lua",
      out .. "/GameData_Spec.lua", out .. "/GameData_Professions.lua" })
    assert.equals(70575, ns.GameData.Build()); assert.equals(2, ns.GameData.Get("ReagentQuality")[2002].rank)
    assert.is_false(ns.GameData.Status(70575).missing)
  end)

  it("fills every Define from the fixtures with the joined values", function()
    local out = tmpdir()
    assert.equals(0, (generate("--build 12.1.5.70575 --cache " .. FIXTURES .. " --out " .. out, out)))
    local ns = load_generated(out)
    for _, name in ipairs(DEFINES) do assert.is_truthy(next(ns.GameData.Get(name)), name .. " is empty") end
    local G = ns.GameData.Get
    assert.same({ professionID = 164, expansionID = 11, concentrationCurrencyID = 3200 }, G("ProfessionLines")[2950])
    assert.same({ matQualityWeight = 1.5 }, G("ReagentCategories")[50])
    assert.same({ categoryID = 80, effects = { { type = "multicraft", amount = 15 } } }, G("OptionalReagents")[5001])
    assert.same({ craftingDifficultyID = 5, difficulty = 250, craftedItemID = 6001 }, G("CraftingData")[600])
    assert.same({ [6001] = 600, [6002] = 600 }, G("ItemCraftingData"))
    assert.same({ [1] = 0, [2] = 50 }, G("QualityThresholds")[5])
    assert.same({ skill = { { 0, 0 }, { 1, 0.5 } }, difficulty = { { 0, 1 } } }, G("ConcentrationCurves")[5])
    assert.same({ [3000] = { effects = { { type = "skill", amount = 1 } }, labels = { 777 } } }, G("SpecEntryEffects"))
    assert.same({ [450001] = { 777 } }, G("RecipeLabels"))
    assert.same({}, ns.GameData.Status(70575).mismatched)
  end)

  it("writes the generated header and is deterministic", function()
    local a, b = tmpdir(), tmpdir()
    generate("--build 12.1.5.70575 --cache " .. FIXTURES .. " --out " .. a, a)
    generate("--build 12.1.5.70575 --cache " .. FIXTURES .. " --out " .. b, b)
    for _, f in ipairs(GENERATED) do
      local text = slurp(a .. "/" .. f)
      local header = "-- GENERATED by tools/gamedata/generate.lua from wago.tools DB2 CSV, build 12.1.5.70575. Do not edit.\n"
        .. "local ADDON_NAME, ns = ...\n"
      assert.equals(header, text:sub(1, #header))
      assert.equals(text, slurp(b .. "/" .. f))
    end
  end)

  it("honours --min-expansion", function()
    local out = tmpdir()
    assert.equals(0, (generate("--build 12.1.5.70575 --cache " .. FIXTURES .. " --out " .. out .. " --min-expansion 10", out)))
    assert.same({ [440001] = { 777 }, [450001] = { 777 } }, load_generated(out).GameData.Get("RecipeLabels"))
  end)

  it("prints Moxie currency candidates and unknown effect types", function()
    local out = tmpdir()
    local code, stdout, stderr = generate("--build 12.1.5.70575 --cache " .. FIXTURES .. " --out " .. out, out)
    assert.equals(0, code)
    assert.truthy(stdout:find("MoxieCurrency candidates:\n3256\tBlacksmithing Moxie\n3257\tTailoring Moxie\n", 1, true), stdout)
    assert.is_nil(stdout:find("Concentration", 1, true))
    assert.truthy(stderr:find("unknown ProfessionEffect type 99 (1 rows)", 1, true), stderr)
  end)

  it("--empty writes ungenerated stubs", function()
    local out = os.tmpname(); os.remove(out); os.execute("mkdir -p " .. out)
    assert.equals(0, run_cmd("lua tools/gamedata/generate.lua --empty --build 12.1.5.70575 --out " .. out .. " >/dev/null"))
    local ns = load_files({}, { "Data/GameData.lua", out .. "/GameData_Reagents.lua" })
    assert.is_true(ns.GameData.Status(70575).missing)
  end)

  it("--empty defines every table with a literal nil build and needs no cache or build", function()
    local out = tmpdir()
    assert.equals(0, (generate("--empty --out " .. out, out)))
    for _, f in ipairs(GENERATED) do
      local text = slurp(out .. "/" .. f)
      assert.truthy(text:find('ns%.GameData%.Define%("%a+", nil, {}%)'), f)
      assert.is_nil(text:find('Define%("%a+", [^n]'), f)
    end
    local ns = load_generated(out)
    for _, name in ipairs(DEFINES) do assert.same({}, ns.GameData.Get(name)) end
    local s = ns.GameData.Status(70575)
    assert.is_nil(s.build); assert.is_true(s.missing); assert.same({}, s.mismatched); assert.is_nil(ns.GameData.Build())
  end)

  it("the checked-in Data files load and report missing data", function()
    local ns = load_files({}, { "Data/GameData.lua", "Data/GameData_Professions.lua", "Data/GameData_Reagents.lua",
      "Data/GameData_Difficulty.lua", "Data/GameData_Spec.lua", "Data/GameData_Manual.lua" })
    for _, name in ipairs(DEFINES) do assert.is_table(ns.GameData.Get(name)) end
    assert.same({}, ns.GameData.Get("MoxieCurrency"))
    assert.is_true(ns.GameData.Status(70575).missing)
  end)

  it("exits 1 with a usage error when --out is missing", function()
    local d = tmpdir()
    local code, _, stderr = generate("--build 12.1.5.70575 --cache " .. FIXTURES, d)
    assert.equals(1, code); assert.truthy(stderr:find("--out", 1, true), stderr)
  end)

  it("rejects a malformed --build", function()
    local d = tmpdir()
    local code, _, stderr = generate("--build 70575 --cache " .. FIXTURES .. " --out " .. d, d)
    assert.equals(1, code); assert.truthy(stderr:find("--build", 1, true), stderr)
  end)

  it("names the missing CSV and how to fetch it", function()
    local cache, out = fixture_copy(), tmpdir()
    os.remove(cache .. "/CurvePoint.csv")
    local code, _, stderr = generate("--build 12.1.5.70575 --cache " .. cache .. " --out " .. out, out)
    assert.equals(1, code)
    assert.truthy(stderr:find("CurvePoint.csv", 1, true), stderr); assert.truthy(stderr:find("fetch.sh 12.1.5.70575", 1, true), stderr)
  end)

  it("reports a wrong field count as a bad export of that table", function()
    local cache, out = fixture_copy(), tmpdir()
    spit(cache .. "/CurvePoint.csv", slurp(cache .. "/CurvePoint.csv") .. "1,2,3\n")
    local code, _, stderr = generate("--build 12.1.5.70575 --cache " .. cache .. " --out " .. out, out)
    assert.equals(1, code)
    assert.truthy(stderr:find("bad export of CurvePoint", 1, true), stderr)
    assert.truthy(stderr:find("line 5 has 3 fields, expected 7", 1, true), stderr)
  end)

  it("names the Define and its tables when a column is missing", function()
    local cache, out = fixture_copy(), tmpdir()
    spit(cache .. "/CraftingQuality.csv", "ID,Tier\n11,1\n")
    local code, _, stderr = generate("--build 12.1.5.70575 --cache " .. cache .. " --out " .. out, out)
    assert.equals(1, code)
    assert.truthy(stderr:find("QualityThresholds", 1, true), stderr); assert.truthy(stderr:find("CraftingQuality", 1, true), stderr)
    assert.truthy(stderr:find("missing column QualityTier", 1, true), stderr)
  end)

  it("writes nothing when generation fails", function()
    local cache, out = fixture_copy(), tmpdir()
    spit(cache .. "/CraftingQuality.csv", "ID,Tier\n11,1\n")
    generate("--build 12.1.5.70575 --cache " .. cache .. " --out " .. out, out)
    for _, f in ipairs(GENERATED) do assert.is_nil(io.open(out .. "/" .. f, "r"), f) end
  end)
end)

describe("tools/gamedata tables and fetch.sh", function()
  local function tables()
    local list = {}
    for line in io.lines("tools/gamedata/tables.txt") do
      line = line:gsub("#.*", ""):match("^%s*(.-)%s*$")
      if line ~= "" then list[#list + 1] = line end
    end
    return list
  end

  it("lists the 20 source tables, each with a fixture CSV", function()
    local list = tables()
    assert.equals(20, #list)
    for _, t in ipairs(list) do assert.is_truthy(io.open(FIXTURES .. "/" .. t .. ".csv", "r"), "no fixture for " .. t) end
  end)

  it("skips tables that are already cached (no network needed)", function()
    local build = "0.0.0.1"
    local dir = "tools/gamedata/cache/" .. build
    os.execute("mkdir -p " .. dir)
    for _, t in ipairs(tables()) do spit(dir .. "/" .. t .. ".csv", "ID\n") end
    local code = run_cmd("bash tools/gamedata/fetch.sh " .. build .. " >/dev/null 2>&1")
    os.execute("rm -rf " .. dir)
    assert.equals(0, code)
  end)

  it("fetch.sh rejects a malformed build", function()
    assert.equals(2, run_cmd("bash tools/gamedata/fetch.sh 70575 >/dev/null 2>&1"))
  end)
end)
