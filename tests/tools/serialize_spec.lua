local serialize = require("serialize")

describe("serialize", function()
  it("is deterministic", function()
    assert.equals('{\n\tfalse,\n\ttrue,\n\t[10] = 3,\n\ta = "x",\n\t["b c"] = 1,\n}',
      serialize({ false, true, a = "x", ["b c"] = 1, [10] = 3 }))
  end)
  it("round-trips floats exactly", function() assert.equals(1/3, loadstring("return " .. serialize(1/3))()) end)
  it("round-trips nested tables", function()
    local t = { { 1, 2 }, k = { z = "q" } }; assert.same(t, loadstring("return " .. serialize(t))())
  end)
  it("rejects functions and cycles", function()
    assert.has_error(function() serialize({ f = print }) end)
    local c = {}; c.c = c; assert.has_error(function() serialize(c) end)
  end)
  it("rejects userdata, NaN and inf", function()
    assert.has_error(function() serialize({ io.stdout }) end)
    assert.has_error(function() serialize(0/0) end)
    assert.has_error(function() serialize({ math.huge }) end)
    assert.has_error(function() serialize({ -math.huge }) end)
  end)
  it("prints integers with %d and floats with the shortest round-trip form", function()
    assert.equals("5", serialize(5)); assert.equals("-3", serialize(-3)); assert.equals("0.5", serialize(0.5))
    assert.equals("0.1", serialize(0.1)); assert.equals("1e+20", serialize(1e20))
    assert.equals("2147483648", serialize(2147483648))
    assert.equals("9007199254740992", serialize(2 ^ 53))
  end)
  it("quotes strings with %q", function()
    assert.equals('"a\\"b"', serialize('a"b'))
    local s = "line1\nline2\0end\\"; assert.equals(s, loadstring("return " .. serialize(s))())
  end)
  it("indents one tab per level with trailing commas", function()
    assert.equals('{\n\t{\n\t\t1,\n\t},\n\tk = {\n\t\tz = "q",\n\t},\n}', serialize({ { 1 }, k = { z = "q" } }))
  end)
  it("prints empty tables compactly", function()
    assert.equals("{}", serialize({})); assert.equals("{\n\t{},\n}", serialize({ {} }))
  end)
  it("orders numeric keys ascending, then strings, after the array part", function()
    assert.equals('{\n\t"a",\n\t"b",\n\t[-1] = 0,\n\t[4] = 1,\n\t[7] = 2,\n\tx = 3,\n\ty = 4,\n}',
      serialize({ "a", "b", y = 4, [7] = 2, x = 3, [4] = 1, [-1] = 0 }))
  end)
  it("quotes keys that are Lua keywords or not identifiers", function()
    assert.equals('{\n\t["1a"] = 2,\n\t_ok = 3,\n\t["end"] = 1,\n}', serialize({ ["end"] = 1, ["1a"] = 2, _ok = 3 }))
  end)
  it("allows shared non-cyclic references", function()
    local shared = { 1 }; local t = serialize({ shared, shared })
    assert.same({ { 1 }, { 1 } }, loadstring("return " .. t)())
  end)
  it("is stable across calls", function()
    local t = {}; for i = 1, 50 do t["k" .. i] = i end
    assert.equals(serialize(t), serialize(t))
  end)
  it("rejects unsupported key types", function()
    assert.has_error(function() serialize({ [true] = 1 }) end)
  end)
end)
