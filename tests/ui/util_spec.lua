describe("ns.UI helpers", function()
  local ns

  before_each(function()
    install_wow_stubs()
    ns = load_addon({}, "UI/Util.lua")
  end)
  after_each(function() _G.GetMoneyString = nil end)

  describe("FormatMoney", function()
    it("starts at the highest non-zero unit", function()
      assert.equals("123g 45s 67c", ns.UI.FormatMoney(1234567))
      assert.equals("1g 0s 0c", ns.UI.FormatMoney(10000))
      assert.equals("1s 20c", ns.UI.FormatMoney(120))
      assert.equals("0c", ns.UI.FormatMoney(0))
      assert.equals("-1g 0s 0c", ns.UI.FormatMoney(-10000))
    end)
    it("returns -- for nil", function() assert.equals("--", ns.UI.FormatMoney(nil)) end)
    it("floors fractional copper", function() assert.equals("1s 20c", ns.UI.FormatMoney(120.9)) end)
    it("uses GetMoneyString in game", function()
      _G.GetMoneyString = function(m) return "M" .. m end
      assert.equals("-M5", ns.UI.FormatMoney(-5)); assert.equals("M5", ns.UI.FormatMoney(5))
    end)
  end)

  describe("ParseMoney", function()
    it("parses money", function()
      assert.equals(123405, ns.UI.ParseMoney("12g 34s 5c")); assert.equals(15000, ns.UI.ParseMoney("1.5"))
      assert.equals(7500, ns.UI.ParseMoney("75s"))
      assert.is_nil(ns.UI.ParseMoney("abc")); assert.is_nil(ns.UI.ParseMoney("-1g")); assert.is_nil(ns.UI.ParseMoney(""))
    end)
    it("accepts any subset of units, any case and no spaces", function()
      assert.equals(10005, ns.UI.ParseMoney("1g5c")); assert.equals(10000, ns.UI.ParseMoney("1G"))
      assert.equals(12, ns.UI.ParseMoney("12c")); assert.equals(15000, ns.UI.ParseMoney("  1.5g "))
      assert.equals(0, ns.UI.ParseMoney("0"))
    end)
    it("rejects garbage, negatives, repeats and non-strings", function()
      assert.is_nil(ns.UI.ParseMoney("1g 2x")); assert.is_nil(ns.UI.ParseMoney("1g 1g"))
      assert.is_nil(ns.UI.ParseMoney("5c 1g")); assert.is_nil(ns.UI.ParseMoney("-5"))
      assert.is_nil(ns.UI.ParseMoney(nil)); assert.is_nil(ns.UI.ParseMoney(12)); assert.is_nil(ns.UI.ParseMoney("   "))
      assert.is_nil(ns.UI.ParseMoney("1..5")); assert.is_nil(ns.UI.ParseMoney("g"))
    end)
  end)

  describe("ParseMoney whitespace and cap", function()
    it("only allows whitespace between unit tokens", function()
      assert.is_nil(ns.UI.ParseMoney("1 5")); assert.is_nil(ns.UI.ParseMoney("12 34"))
      assert.is_nil(ns.UI.ParseMoney("1 g")); assert.is_nil(ns.UI.ParseMoney("1g 5 0s"))
      assert.equals(15000, ns.UI.ParseMoney("1g 50s")); assert.equals(15000, ns.UI.ParseMoney("  1g   50s  "))
      assert.equals(15000, ns.UI.ParseMoney("1g50s"))
    end)
    it("rejects values above the gold cap", function()
      assert.equals(99999990000, ns.UI.ParseMoney("9999999g")); assert.is_nil(ns.UI.ParseMoney("9999999g 1c"))
      assert.is_nil(ns.UI.ParseMoney("10000000g")); assert.is_nil(ns.UI.ParseMoney("99999999999999"))
      assert.is_nil(ns.UI.ParseMoney("10000000"))
    end)
  end)

  describe("ParseItemID", function()
    it("parses item ids", function()
      assert.equals(12345, ns.UI.ParseItemID("12345"))
      assert.equals(191460, ns.UI.ParseItemID("|cff0070dd|Hitem:191460::::::::70:::::|h[Ore]|h|r"))
      assert.is_nil(ns.UI.ParseItemID("abc"))
    end)
    it("trims, and rejects zero, empty and non-strings", function()
      assert.equals(7, ns.UI.ParseItemID("  7 ")); assert.is_nil(ns.UI.ParseItemID("0"))
      assert.is_nil(ns.UI.ParseItemID("")); assert.is_nil(ns.UI.ParseItemID(nil)); assert.is_nil(ns.UI.ParseItemID(5))
      assert.is_nil(ns.UI.ParseItemID("12a"))
    end)
  end)

  describe("FormatAge", function()
    it("formats ages", function()
      assert.equals("never", ns.UI.FormatAge(nil)); assert.equals("<1m", ns.UI.FormatAge(59))
      assert.equals("1m", ns.UI.FormatAge(60)); assert.equals("59m", ns.UI.FormatAge(3599))
      assert.equals("1h", ns.UI.FormatAge(3600)); assert.equals("23h", ns.UI.FormatAge(86399))
      assert.equals("1d", ns.UI.FormatAge(86400)); assert.equals("3d", ns.UI.FormatAge(86400 * 3.5))
    end)
    it("treats negative ages as under a minute", function() assert.equals("<1m", ns.UI.FormatAge(-5)) end)
  end)

  describe("JoinList", function()
    it("joins with a comma and a space", function()
      assert.equals("a, b", ns.UI.JoinList({ "a", "b" }))
      assert.equals("a", ns.UI.JoinList({ "a" }))
    end)
    it("returns an empty text for an empty list", function() assert.equals("", ns.UI.JoinList({})) end)
    it("takes the separator from the locale at call time", function()
      setmetatable(ns.L, { __index = function(_, key) return "T:" .. key end })
      assert.equals("aT:, b", ns.UI.JoinList({ "a", "b" }))
    end)
  end)
end)
