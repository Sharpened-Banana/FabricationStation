describe("RecipeListLabels", function()
  local INITIALIZED = "OnInitializedFrame"

  local function count(list, owner)
    local n = 0
    for _, entry in ipairs(list or {}) do if entry.owner == owner then n = n + 1 end end
    return n
  end

  local function labelled_world(opts)
    opts = opts or {}
    opts.last = "UI/RecipeListLabels.lua"
    opts.calibrate = opts.calibrate or { ["Main-Realm"] = { 9001 } }
    local ns, W, world = make_world(opts)
    local form = fake_professions_frame({ loaded = true })
    W.fire("ADDON_LOADED", "Blizzard_Professions")
    return ns, W, world, form
  end

  local function recipe_node(form, recipeID) return form.node({ recipeInfo = { recipeID = recipeID } }) end
  local function text_of(form, row) return (form.fontStringsOf(row)[1] or {}).GetText and form.fontStringsOf(row)[1]:GetText() end

  describe("LabelText", function()
    local L
    before_each(function()
      local ns = make_world({ last = "UI/RecipeListLabels.lua" }); L = ns.UI.RecipeListLabels
    end)

    it("label text", function()
      assert.same({ "+12g", "green" }, { L.LabelText({ profit = 120010, flags = {} }) })
      assert.same({ "-3g", "red" }, { L.LabelText({ profit = -30000, flags = {} }) })
      assert.same({ "?", "grey" }, { L.LabelText({ flags = { noPrice = true } }) })
      assert.same({ "+45s", "green" }, { L.LabelText({ profit = 4500, flags = {} }) })
    end)
    it("shows amounts under 1g in silver, and under 1s in copper", function()
      assert.same({ "-45s", "red" }, { L.LabelText({ profit = -4500, flags = {} }) })
      assert.same({ "+99s", "green" }, { L.LabelText({ profit = 9999, flags = {} }) })
      assert.same({ "+50c", "green" }, { L.LabelText({ profit = 50, flags = {} }) })
      assert.same({ "-7c", "red" }, { L.LabelText({ profit = -7, flags = {} }) })
    end)
    it("rounds gold down so a profit is never overstated", function()
      assert.same({ "+12g", "green" }, { L.LabelText({ profit = 129999, flags = {} }) })
      assert.same({ "-12g", "red" }, { L.LabelText({ profit = -129999, flags = {} }) })
      assert.same({ "+1g", "green" }, { L.LabelText({ profit = 10000, flags = {} }) })
    end)
    it("shows an even recipe as 0g in grey", function()
      assert.same({ "0g", "grey" }, { L.LabelText({ profit = 0, flags = {} }) })
    end)
    it("a nil profit is a question mark, never 0g", function()
      assert.same({ "?", "grey" }, { L.LabelText({ flags = {} }) })
      assert.same({ "?", "grey" }, { L.LabelText({}) })
      assert.same({ "?", "grey" }, { L.LabelText({ profit = 0 / 0, flags = {} }) })
    end)
    it("an infinite profit is a question mark", function()
      assert.same({ "?", "grey" }, { L.LabelText({ profit = math.huge, flags = {} }) })
      assert.same({ "?", "grey" }, { L.LabelText({ profit = -math.huge, flags = {} }) })
    end)
    it("an estimated profit starts with a tilde", function()
      assert.same({ "~+12g", "green" }, { L.LabelText({ profit = 120010, flags = { estimated = true } }) })
      assert.same({ "~-3g?", "red" }, { L.LabelText({ profit = -30000, flags = { estimated = true, noPrice = true } }) })
      assert.same({ "~0g", "grey" }, { L.LabelText({ profit = 0, flags = { estimated = true } }) })
      assert.same({ "?", "grey" }, { L.LabelText({ flags = { estimated = true } }) })
    end)
    it("a profit with some prices missing keeps its colour and gets a question mark", function()
      assert.same({ "+12g?", "green" }, { L.LabelText({ profit = 120010, flags = { noPrice = true } }) })
      assert.same({ "-3g?", "red" }, { L.LabelText({ profit = -30000, flags = { noPrice = true } }) })
    end)
  end)

  it("labels rows without writing fields on them", function()
    local ns, W, world = make_world({ last = "UI/RecipeListLabels.lua", calibrate = { ["Main-Realm"] = { 9001 } } })
    local form = fake_professions_frame(); W.fire("ADDON_LOADED", "Blizzard_Professions")
    local row = form.newRow()
    form.recipeScrollBox.fireInitialized(row, form.node({ recipeInfo = { recipeID = 9001 } }))
    assert.equals("+12g", form.fontStringsOf(row)[1]:GetText())
    assert.same({}, form.assignedFields)
    assert.is_not_nil(ns); assert.is_not_nil(world)
  end)

  it("makes one small overlay font string per row, right-aligned, coloured by the sign", function()
    local _, _, _, form = labelled_world()
    local row = form.newRow()
    form.recipeScrollBox.fireInitialized(row, recipe_node(form, 9001))
    form.recipeScrollBox.fireInitialized(row, recipe_node(form, 9001))
    local fontStrings = form.fontStringsOf(row)
    assert.equals(1, #fontStrings)
    assert.equals("GameFontNormalSmall", fontStrings[1].template)
    assert.equals("OVERLAY", fontStrings[1].layer)
    assert.same({ 0.25, 1, 0.25 }, { fontStrings[1]:GetTextColor() })
    assert.is_true(fontStrings[1]:IsShown())
  end)

  it("colours a loss red and a missing price grey", function()
    local _, _, world, form = labelled_world()
    world.fakeEvaluate(9001, { profit = -30000, flags = {} })
    local row = form.newRow()
    form.recipeScrollBox.fireInitialized(row, recipe_node(form, 9001))
    assert.equals("-3g", text_of(form, row))
    assert.same({ 1, 0.25, 0.25 }, { form.fontStringsOf(row)[1]:GetTextColor() })
    world.fakeEvaluate(9001, { flags = { noPrice = true } })
    form.recipeScrollBox.fireInitialized(row, recipe_node(form, 9001))
    assert.equals("?", text_of(form, row))
    assert.same({ 0.62, 0.62, 0.62 }, { form.fontStringsOf(row)[1]:GetTextColor() })
  end)

  it("evaluates for the current character with default options", function()
    local _, _, world, form = labelled_world()
    world.fakeEvaluate(9001, { profit = 100, flags = {} })
    form.recipeScrollBox.fireInitialized(form.newRow(), recipe_node(form, 9001))
    assert.equals(1, #world.evaluated)
    assert.equals("Main-Realm", world.evaluated[1].charKey)
    assert.same({}, world.evaluated[1].opts)
  end)

  it("skips category rows and hides the label of a recycled row that becomes one", function()
    local _, _, _, form = labelled_world()
    local category = form.newRow()
    form.recipeScrollBox.fireInitialized(category, form.node({ categoryInfo = { name = "Armor" } }))
    assert.equals(0, #form.fontStringsOf(category))

    local row = form.newRow()
    form.recipeScrollBox.fireInitialized(row, recipe_node(form, 9001))
    assert.is_true(form.fontStringsOf(row)[1]:IsShown())
    form.recipeScrollBox.fireInitialized(row, form.node({ categoryInfo = { name = "Armor" } }))
    assert.is_false(form.fontStringsOf(row)[1]:IsShown())
    form.recipeScrollBox.fireInitialized(row, recipe_node(form, 9001))
    assert.is_true(form.fontStringsOf(row)[1]:IsShown())
    assert.equals(1, #form.fontStringsOf(row))
  end)

  it("hides the label when the recipe cannot be evaluated yet", function()
    local _, _, _, form = labelled_world()
    local row = form.newRow()
    form.recipeScrollBox.fireInitialized(row, recipe_node(form, 9001))
    assert.is_true(form.fontStringsOf(row)[1]:IsShown())
    form.recipeScrollBox.fireInitialized(row, recipe_node(form, 424242))
    assert.is_false(form.fontStringsOf(row)[1]:IsShown())
  end)

  it("hides the label of a recipe the character does not know", function()
    local _, _, world, form = labelled_world()
    local row = form.newRow()
    form.recipeScrollBox.fireInitialized(row, recipe_node(form, 9001))
    assert.is_true(form.fontStringsOf(row)[1]:IsShown())
    world.fakeEvaluate(9001, { profit = 100, flags = { unknownRecipe = true } })
    form.recipeScrollBox.fireInitialized(row, recipe_node(form, 9001))
    assert.is_false(form.fontStringsOf(row)[1]:IsShown())
  end)

  it("relabels every visible row on FS_RECIPES_CHANGED", function()
    local ns, W, world, form = labelled_world()
    local a, b = form.newRow(), form.newRow()
    form.recipeScrollBox.fireInitialized(a, recipe_node(form, 9001))
    form.recipeScrollBox.fireInitialized(b, recipe_node(form, 9001))
    world.fakeEvaluate(9001, { profit = 45000, flags = {} })
    ns.FS:SendMessage(ns.Msg.RECIPES_CHANGED)
    assert.equals("+4g", text_of(form, a)); assert.equals("+4g", text_of(form, b))
    assert.is_not_nil(W)
    assert.same({}, form.assignedFields)
  end)

  it("labels rows that were already on screen when it attached", function()
    local _, W = make_world({ last = "UI/RecipeListLabels.lua", calibrate = { ["Main-Realm"] = { 9001 } } })
    local form = fake_professions_frame()
    local row = form.newRow()
    form.recipeScrollBox.fireInitialized(row, recipe_node(form, 9001))
    assert.equals(0, #form.fontStringsOf(row))
    W.fire("ADDON_LOADED", "Blizzard_Professions")
    assert.equals("+12g", text_of(form, row))
  end)

  it("hides every label when the module is switched off and shows them again when it is back on", function()
    local ns, _, _, form = labelled_world()
    local a, b = form.newRow(), form.newRow()
    form.recipeScrollBox.fireInitialized(a, recipe_node(form, 9001))
    form.recipeScrollBox.fireInitialized(b, recipe_node(form, 9001))
    ns.FS:SetModuleEnabled("RecipeListLabels", false)
    assert.is_false(form.fontStringsOf(a)[1]:IsShown()); assert.is_false(form.fontStringsOf(b)[1]:IsShown())
    assert.equals(0, #(form.scrollCallbacks[INITIALIZED] or {}))
    -- a recycled row initialised while the module is off gets no label
    local c = form.newRow()
    form.recipeScrollBox.fireInitialized(c, recipe_node(form, 9001))
    assert.equals(0, #form.fontStringsOf(c))
    ns.FS:SetModuleEnabled("RecipeListLabels", true)
    assert.is_true(form.fontStringsOf(a)[1]:IsShown()); assert.equals("+12g", text_of(form, a))
    assert.equals("+12g", text_of(form, c))
    assert.equals(1, #form.scrollCallbacks[INITIALIZED])
    assert.same({}, form.assignedFields)
  end)

  it("stops labelling after the module is switched off, including on FS_RECIPES_CHANGED", function()
    local ns, _, world, form = labelled_world()
    local row = form.newRow()
    form.recipeScrollBox.fireInitialized(row, recipe_node(form, 9001))
    ns.FS:SetModuleEnabled("RecipeListLabels", false)
    world.fakeEvaluate(9001, { profit = 45000, flags = {} })
    ns.FS:SendMessage(ns.Msg.RECIPES_CHANGED)
    assert.equals("+12g", text_of(form, row))
    assert.is_false(form.fontStringsOf(row)[1]:IsShown())
  end)

  it("attaches_when_professions_already_loaded", function()
    local ns, W, world = make_world({ last = "UI/RecipeListLabels.lua", professions = {},
      calibrate = { ["Main-Realm"] = { 9001 } } })
    local form = world.form
    local module = ns.FS:GetModule("RecipeListLabels")
    assert.equals(1, count(form.scrollCallbacks[INITIALIZED], module))
    W.fire("ADDON_LOADED", "Blizzard_Professions")
    assert.equals(1, count(form.scrollCallbacks[INITIALIZED], module))
    local row = form.newRow()
    form.recipeScrollBox.fireInitialized(row, recipe_node(form, 9001))
    assert.equals("+12g", text_of(form, row))
    assert.same({}, form.assignedFields)
  end)

  it("does not attach while Blizzard_Professions is not loaded", function()
    local ns, W = make_world({ last = "UI/RecipeListLabels.lua" })
    assert.is_true(ns.FS:GetModule("RecipeListLabels"):IsEnabled())
    W.fire("ADDON_LOADED", "Some_Other_Addon")
    local form = fake_professions_frame()
    assert.equals(0, #(form.scrollCallbacks[INITIALIZED] or {}))
  end)

  it("disables_when_scrollbox_missing", function()
    local ns, W = make_world({ last = "UI/RecipeListLabels.lua" }); fake_professions_frame({ withoutScrollBox = true })
    assert.has_no.errors(function() W.fire("ADDON_LOADED", "Blizzard_Professions") end)
    assert.is_false(ns.FS:GetModule("RecipeListLabels"):IsEnabled())
    assert.is_string(ns.FS.failedModules.RecipeListLabels)
    assert.is_truthy(ns.FS.failedModules.RecipeListLabels:find("recipe list ScrollBox not found", 1, true))
  end)

  it("disables_when_scrollbox_missing_at_enable", function()
    local ns = make_world({ last = "UI/RecipeListLabels.lua", professions = { withoutScrollBox = true } })
    assert.is_false(ns.FS:GetModule("RecipeListLabels"):IsEnabled())
  end)

  it("an error while labelling turns off only this module", function()
    local ns, _, world, form = labelled_world()
    local row = form.newRow()
    world.fakeEvaluate(9001, function() error("boom") end)
    assert.has_no.errors(function() form.recipeScrollBox.fireInitialized(row, recipe_node(form, 9001)) end)
    assert.is_false(ns.FS:GetModule("RecipeListLabels"):IsEnabled())
    assert.is_true(ns.FS:GetModule("Recipes"):IsEnabled())
    assert.equals(0, #(form.scrollCallbacks[INITIALIZED] or {}))
  end)

  it("is a toggleable module, not a core one", function()
    local ns = make_world({ last = "UI/RecipeListLabels.lua" })
    local module = ns.FS:GetModule("RecipeListLabels")
    assert.is_falsy(module.coreModule)
    assert.is_true(ns.FS:SetModuleEnabled("RecipeListLabels", false))
    assert.is_false(module:IsEnabled())
    assert.is_false(ns.FS.db.global.settings.modules.RecipeListLabels)
  end)
end)

-- Hotfix H1-6: labels overlapped long recipe names. The label sits left of the lock icon's place and hides when
-- Blizzard's name (+ craftable count) text would reach it; Blizzard's font strings are only read.
describe("H1-6 RecipeListLabels and long names", function()
  local ns, world, form
  before_each(function()
    local W
    ns, W, world = make_world({ last = "UI/RecipeListLabels.lua", calibrate = { ["Main-Realm"] = { 9001 } } })
    form = fake_professions_frame({ loaded = true })
    W.fire("ADDON_LOADED", "Blizzard_Professions")
    world.fakeEvaluate(9001, { profit = 120010, flags = {} })   -- "+12g": 4 characters, 24 wide in the fake
  end)
  local function label_of(row) return form.fontStringsOf(row)[1] end
  local function show(row) form.recipeScrollBox.fireInitialized(row, form.node({ recipeInfo = { recipeID = 9001 } })) end

  -- Row from x = 100 to 400; the label is anchored 17 + 4 left of the row's right edge, so it starts at
  -- 400 - 21 - 24 = 355 and needs the text to end by 351.
  it("anchors the label left of the lock icon's place", function()
    local row = form.newRow({ left = 100, width = 300, label = { right = 200, width = 80 } })
    show(row)
    assert.same({ "RIGHT", row, "RIGHT", -21, 0 }, label_of(row).points[1])
  end)

  it("shows the label beside a short name", function()
    local row = form.newRow({ left = 100, width = 300, label = { right = 200, width = 80 } })
    show(row)
    assert.is_true(label_of(row):IsShown())
  end)

  it("hides the label when a long name reaches it", function()
    local row = form.newRow({ left = 100, width = 300, label = { right = 370, width = 250 } })
    show(row)
    assert.is_false(label_of(row):IsShown())
  end)

  it("counts Blizzard's craftable count after the name", function()
    local row = form.newRow({ left = 100, width = 300, label = { right = 320, width = 200 },
      count = { shown = true, right = 360, stringWidth = 40 } })
    show(row)
    assert.is_false(label_of(row):IsShown())
    row = form.newRow({ left = 100, width = 300, label = { right = 280, width = 160 },
      count = { shown = true, right = 320, stringWidth = 40 } })
    show(row)
    assert.is_true(label_of(row):IsShown())
  end)

  it("measures from the widths when the positions are not laid out yet", function()
    -- Name starts at 26 - 9 + 4 = 21 from the row's left edge; 21 + 250 = 271 > 351 - 100 = 251.
    local long = form.newRow({ width = 300, label = { width = 250 } })
    show(long)
    assert.is_false(label_of(long):IsShown())
    local short = form.newRow({ width = 300, label = { width = 120 } })
    show(short)
    assert.is_true(label_of(short):IsShown())
  end)

  it("shows the label again when the recycled row holds a short name", function()
    local geometry = { left = 100, width = 300, label = { right = 370, width = 250 } }
    local row = form.newRow(geometry)
    show(row)
    assert.is_false(label_of(row):IsShown())
    geometry.label.right, geometry.label.width = 200, 80
    show(row)
    assert.is_true(label_of(row):IsShown())
  end)

  it("only reads Blizzard's row parts: no writes, no SetWidth", function()
    local row = form.newRow({ left = 100, width = 300, label = { right = 370, width = 250 },
      count = { shown = true, right = 390, stringWidth = 20 } })
    show(row)
    assert.same({}, form.assignedFields)
    assert.is_truthy(form.rowReads["Label:GetRight"] or form.rowReads["Count:GetRight"])
    assert.is_not_nil(ns)
  end)
end)
