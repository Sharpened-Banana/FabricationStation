local P2 = require("tests.helpers.phase2")
describe("Customers tags/links/search/export", function()
  local ns, C
  before_each(function()
    ns = P2.boot(); P2.load(ns, {"Modules/Customers.lua"}); C = ns.FS:GetModule("Customers")
    C:RecordOrder("Bob-Silvermoon", {time=1000, orderID=1, itemID=1, recipeID=1, quality=3, tip=500000, commission=450000, orderType="personal"})
  end)
  it("blocks a whole linked group", function()
    C:Link("Alt-Silvermoon", "Bob-Silvermoon"); C:SetTag("Bob-Silvermoon", "blocked", true)
    assert.is_true(C:IsBlocked("Alt-Silvermoon")); assert.is_false(C:IsBlocked("Nobody-Silvermoon"))
    assert.same({"Bob-Silvermoon", "Alt-Silvermoon"}, C:GetGroup("Alt-Silvermoon"))
  end)
  it("refuses cycles and self links", function()
    C:Link("Alt-Silvermoon", "Bob-Silvermoon")
    assert.same({false, "cycle"}, {C:Link("Bob-Silvermoon", "Alt-Silvermoon")})
    assert.same({false, "self"}, {C:Link("Bob-Silvermoon", "Bob-Silvermoon")})
  end)
  it("searches names, notes and tags", function()
    C:SetTag("Bob-Silvermoon", "VIP", true); C:SetNote("Ann-Silvermoon", "slow payer")
    assert.equal("Bob-Silvermoon", C:Search("vip")[1].nameRealm)
    assert.equal("Ann-Silvermoon", C:Search("SLOW")[1].nameRealm)
    assert.equal(2, #C:Search(""))
  end)
  it("exports CSV with quoting", function()
    C:SetTag("Bob-Silvermoon", "VIP", true); C:SetTag("Bob-Silvermoon", "blocked", true)
    C:SetNote("Bob-Silvermoon", 'pays well, "fast"\nalways')
    assert.equal('nameRealm,orders,tipsTotal,lastSeen,tags,linkedTo,notes\n'
      .. 'Bob-Silvermoon,1,500000,1970-01-01,VIP;blocked,,"pays well, ""fast"" always"',
      C:Export({"Bob-Silvermoon"}))
  end)

  describe("notes", function()
    it("sets a note, creates a missing record and sends once per real change", function()
      spy.on(C, "SendMessage")
      C:SetNote("Ann", "hello"); C:SetNote("Ann", "hello")
      assert.equal("hello", C:Get("Ann-Silvermoon").notes)
      assert.same({}, C:Get("Ann-Silvermoon").orders)
      assert.spy(C.SendMessage).was.called(1)
      assert.spy(C.SendMessage).was.called_with(C, "FS_CUSTOMERS_CHANGED", "Ann-Silvermoon")
      C:SetNote("Ann", "")
      assert.equal("", C:Get("Ann-Silvermoon").notes)
      assert.spy(C.SendMessage).was.called(2)
    end)
    it("creates nothing for an empty note on an unknown customer or a bad name", function()
      spy.on(C, "SendMessage")
      C:SetNote("Ann", ""); C:SetNote("Ann", nil); C:SetNote(nil, "x"); C:SetNote("  ", "x")
      assert.is_nil(C:Get("Ann-Silvermoon"))
      assert.spy(C.SendMessage).was_not.called()
    end)
    it("does not disturb the order history, and a later order sets the first-seen time", function()
      C:SetNote("Bob", "x")
      assert.equal(1, #C:Get("Bob-Silvermoon").orders); assert.equal(1000, C:Get("Bob-Silvermoon").firstSeen)
      C:SetNote("Ann", "x")
      C:RecordOrder("Ann", {time=2000, orderID=5, tip=7})
      local r = C:Get("Ann-Silvermoon")
      assert.equal(2000, r.firstSeen); assert.equal(2000, r.lastSeen); assert.equal("x", r.notes)
    end)
  end)

  describe("tags", function()
    it("adds and removes a tag, sending only on a real change", function()
      spy.on(C, "SendMessage")
      C:SetTag("Bob", "VIP", true); C:SetTag("Bob", "VIP", true)
      assert.is_true(C:Get("Bob-Silvermoon").tags.VIP)
      assert.spy(C.SendMessage).was.called(1)
      C:SetTag("Bob", "VIP", false); C:SetTag("Bob", "VIP", false)
      assert.is_nil(C:Get("Bob-Silvermoon").tags.VIP)
      assert.spy(C.SendMessage).was.called(2)
    end)
    it("creates a missing record when a tag is turned on, but not when turned off", function()
      C:SetTag("Ann", "VIP", false)
      assert.is_nil(C:Get("Ann-Silvermoon"))
      C:SetTag("Ann", "VIP", true)
      assert.is_true(C:Get("Ann-Silvermoon").tags.VIP)
    end)
    it("keeps VIP and blocked canonical whatever the case or spacing", function()
      C:SetTag("Bob", " vip ", true); C:SetTag("Bob", "BLOCKED", true)
      assert.same({VIP = true, blocked = true}, C:Get("Bob-Silvermoon").tags)
      C:SetTag("Bob", "Vip", false)
      assert.same({blocked = true}, C:Get("Bob-Silvermoon").tags)
    end)
    it("trims a custom tag, cuts it to 24 characters and ignores an empty one", function()
      spy.on(C, "SendMessage")
      C:SetTag("Bob", "  friend  ", true)
      C:SetTag("Bob", string.rep("x", 30), true)
      C:SetTag("Bob", "   ", true); C:SetTag("Bob", "", true); C:SetTag("Bob", nil, true)
      assert.same({friend = true, [string.rep("x", 24)] = true}, C:Get("Bob-Silvermoon").tags)
      assert.spy(C.SendMessage).was.called(2)
    end)
    it("does not cut a multibyte character in half", function()
      local tag = string.rep("\195\169", 30)   -- 30 characters, 60 bytes
      C:SetTag("Bob", tag, true)
      assert.is_true(C:Get("Bob-Silvermoon").tags[string.rep("\195\169", 24)])
    end)
    it("repairs a record whose tags table is missing", function()
      ns.FS.db.global.customers["Bob-Silvermoon"].tags = nil
      C:SetTag("Bob", "VIP", true)
      assert.is_true(C:Get("Bob-Silvermoon").tags.VIP)
    end)
  end)

  describe("links", function()
    it("links an alt to the root of the main and creates both records", function()
      spy.on(C, "SendMessage")
      assert.is_true(C:Link("Alt", "Main"))
      assert.equal("Main-Silvermoon", C:Get("Alt-Silvermoon").linkedTo)
      assert.is_table(C:Get("Main-Silvermoon"))
      assert.spy(C.SendMessage).was.called_with(C, "FS_CUSTOMERS_CHANGED", "Alt-Silvermoon")
      assert.spy(C.SendMessage).was.called_with(C, "FS_CUSTOMERS_CHANGED", "Main-Silvermoon")
    end)
    it("sends nothing when the link is already there", function()
      C:Link("Alt", "Bob")
      spy.on(C, "SendMessage")
      assert.is_true(C:Link("Alt", "Bob"))
      assert.spy(C.SendMessage).was_not.called()
    end)
    it("points a link at the root of a chain", function()
      C:Link("A2", "A1"); C:Link("A3", "A2")
      assert.equal("A1-Silvermoon", C:Get("A3-Silvermoon").linkedTo)
      assert.equal("A1-Silvermoon", C:Root("A3"))
      assert.equal("A1-Silvermoon", C:Root("A1-Silvermoon"))
      assert.equal("Zed-Silvermoon", C:Root("Zed"))
      assert.is_nil(C:Root(nil))
    end)
    it("refuses a cycle through a longer chain and a self link by short name", function()
      C:Link("B", "A"); C:Link("C", "B")
      assert.same({false, "cycle"}, {C:Link("A", "C")})
      assert.same({false, "self"}, {C:Link("A", "A-Silvermoon")})
      assert.is_nil(C:Get("A-Silvermoon").linkedTo)
    end)
    it("re-roots an alt that has alts of its own", function()
      C:Link("Alt2", "Alt1"); C:Link("Alt1", "Main")
      assert.equal("Main-Silvermoon", C:Root("Alt2"))
      assert.same({"Main-Silvermoon", "Alt1-Silvermoon", "Alt2-Silvermoon"}, C:GetGroup("Alt2"))
    end)
    it("moves an alt to another main", function()
      C:Link("Alt", "Bob"); C:Link("Alt", "Ann")
      assert.equal("Ann-Silvermoon", C:Get("Alt-Silvermoon").linkedTo)
      assert.same({"Bob-Silvermoon"}, C:GetGroup("Bob"))
    end)
    it("rejects missing names", function()
      assert.same({false, "invalid"}, {C:Link(nil, "Bob")})
      assert.same({false, "invalid"}, {C:Link("Alt", "  ")})
    end)
    it("unlinks an alt, sending only when it was linked", function()
      C:Link("Alt", "Bob")
      spy.on(C, "SendMessage")
      assert.is_true(C:Unlink("Alt"))
      assert.is_nil(C:Get("Alt-Silvermoon").linkedTo)
      assert.is_false(C:IsBlocked("Alt"))
      local calls = #C.SendMessage.calls
      assert.is_false(C:Unlink("Alt")); assert.is_false(C:Unlink("Nobody")); assert.is_false(C:Unlink(nil))
      assert.equal(calls, #C.SendMessage.calls)
      assert.same({"Bob-Silvermoon"}, C:GetGroup("Bob"))
    end)
    it("sorts the alts after the root and lists an unknown name alone", function()
      C:Link("Zed", "Bob"); C:Link("Amy", "Bob")
      assert.same({"Bob-Silvermoon", "Amy-Silvermoon", "Zed-Silvermoon"}, C:GetGroup("Bob"))
      assert.same({"Nobody-Silvermoon"}, C:GetGroup("Nobody"))
      assert.same({}, C:GetGroup(nil))
    end)
    it("survives a damaged link loop", function()
      ns.FS.db.global.customers["A-Silvermoon"] = {nameRealm = "A-Silvermoon", linkedTo = "B-Silvermoon"}
      ns.FS.db.global.customers["B-Silvermoon"] = {nameRealm = "B-Silvermoon", linkedTo = "A-Silvermoon"}
      assert.is_string(C:Root("A")); assert.is_table(C:GetGroup("A")); assert.is_false(C:IsBlocked("A"))
    end)
  end)

  describe("IsBlocked", function()
    it("is false for a plain, unblocked or unknown customer", function()
      assert.is_false(C:IsBlocked("Bob")); assert.is_false(C:IsBlocked(nil)); assert.is_false(C:IsBlocked(""))
    end)
    it("accepts a short name and follows the block from an alt to the main", function()
      C:Link("Alt", "Bob"); C:SetTag("Alt", "blocked", true)
      assert.is_true(C:IsBlocked("Bob")); assert.is_true(C:IsBlocked("Bob-Silvermoon")); assert.is_true(C:IsBlocked("Alt"))
      C:Unlink("Alt")
      assert.is_false(C:IsBlocked("Bob")); assert.is_true(C:IsBlocked("Alt"))
    end)
    it("reads fine without a database", function()
      ns.FS.db = nil
      assert.is_false(C:IsBlocked("Bob"))
      assert.same({}, C:Search("")); assert.equal("nameRealm,orders,tipsTotal,lastSeen,tags,linkedTo,notes", C:Export())
    end)
  end)

  describe("Search", function()
    it("matches a plain substring, not a pattern", function()
      C:SetNote("Ann", "50% off (friend)")
      assert.equal(1, #C:Search("50%")); assert.equal(1, #C:Search("(friend)"))
      assert.equal(0, #C:Search(".")); assert.equal(0, #C:Search("zzz"))
    end)
    it("finds a custom tag and a name part, ignoring case and outer spaces", function()
      C:SetTag("Ann", "Guild Mate", true)
      assert.equal("Ann-Silvermoon", C:Search("  guild mate ")[1].nameRealm)
      assert.equal("Bob-Silvermoon", C:Search("BOB")[1].nameRealm)
      assert.equal(2, #C:Search("silvermoon"))
    end)
    it("sorts by last seen, newest first, a record never seen last, then by name", function()
      C:RecordOrder("Cy", {time=3000, orderID=9, tip=1})
      C:RecordOrder("Dee", {time=3000, orderID=10, tip=1})
      C:SetNote("Ann", "x")                       -- no orders: nothing seen
      C:SetNote("Abe", "x")
      local names = {}
      for i, r in ipairs(C:Search("")) do names[i] = r.nameRealm end
      assert.same({"Cy-Silvermoon", "Dee-Silvermoon", "Bob-Silvermoon", "Abe-Silvermoon", "Ann-Silvermoon"}, names)
    end)
    it("returns the saved records and tolerates a damaged one", function()
      ns.FS.db.global.customers["Odd-Silvermoon"] = {notes = 5, tags = "x"}
      ns.FS.db.global.customers["Junk-Silvermoon"] = "junk"
      local found = C:Search("")
      assert.equal(2, #found)
      assert.equal(C:Get("Bob-Silvermoon"), found[1])
      assert.equal(ns.FS.db.global.customers["Odd-Silvermoon"], C:Search("odd")[1])
    end)
  end)

  describe("Export", function()
    it("exports every customer, sorted by name, when given no list", function()
      C:SetNote("Ann", "hi")
      C:Link("Alt", "Bob")
      local lines = {}
      for line in (C:Export() .. "\n"):gmatch("(.-)\n") do lines[#lines + 1] = line end
      assert.same({
        "nameRealm,orders,tipsTotal,lastSeen,tags,linkedTo,notes",
        "Alt-Silvermoon,0,0,,,Bob-Silvermoon,",
        "Ann-Silvermoon,0,0,,,,hi",
        "Bob-Silvermoon,1,500000,1970-01-01,,,",
      }, lines)
    end)
    it("keeps the order of the list, normalizes names and skips unknown ones", function()
      C:SetNote("Ann", "hi")
      local out = C:Export({"Ann", "Nobody", "Bob-Silvermoon"})
      assert.equal("nameRealm,orders,tipsTotal,lastSeen,tags,linkedTo,notes\nAnn-Silvermoon,0,0,,,,hi\n"
        .. "Bob-Silvermoon,1,500000,1970-01-01,,,", out)
      assert.equal("nameRealm,orders,tipsTotal,lastSeen,tags,linkedTo,notes", C:Export({}))
    end)
    it("sorts tags by byte order, joins them with semicolons and quotes a field that needs it", function()
      C:SetTag("Bob", "zeta", true); C:SetTag("Bob", "VIP", true); C:SetTag("Bob", "a,b", true)
      assert.equal('Bob-Silvermoon,1,500000,1970-01-01,"VIP;a,b;zeta",,',
        C:Export({"Bob"}):match("\n(.*)$"))
    end)
    it("turns CR and CRLF newlines into one space", function()
      C:SetNote("Bob", "a\r\nb\rc\nd")
      assert.equal("a b c d", C:Export({"Bob"}):match(",([^,]*)$"))
    end)
    it("is a plain string that changes nothing", function()
      local before = ns.FS.db.global.customers["Bob-Silvermoon"].notes
      assert.is_string(C:Export())
      assert.equal(before, ns.FS.db.global.customers["Bob-Silvermoon"].notes)
    end)
  end)

  describe("while the saved data is from a newer version", function()
    before_each(function() ns.FS.dbIsNewer = true; spy.on(C, "SendMessage") end)
    it("writes nothing and sends nothing", function()
      C:SetNote("Bob", "x"); C:SetNote("Ann", "x"); C:SetTag("Bob", "VIP", true); C:SetTag("Ann", "VIP", true)
      assert.same({false, "readonly"}, {C:Link("Alt", "Bob")})
      assert.is_false(C:Unlink("Alt"))
      assert.equal("", C:Get("Bob-Silvermoon").notes); assert.same({}, C:Get("Bob-Silvermoon").tags)
      assert.is_nil(C:Get("Ann-Silvermoon")); assert.is_nil(C:Get("Alt-Silvermoon"))
      assert.spy(C.SendMessage).was_not.called()
    end)
    it("leaves an existing link alone, and still reads", function()
      ns.FS.dbIsNewer = nil
      C:Link("Alt", "Bob"); C:SetTag("Bob", "blocked", true)
      ns.FS.dbIsNewer = true
      assert.is_false(C:Unlink("Alt"))
      assert.equal("Bob-Silvermoon", C:Get("Alt-Silvermoon").linkedTo)
      assert.is_true(C:IsBlocked("Alt")); assert.equal(2, #C:Search("")); assert.is_string(C:Export())
    end)
  end)
end)
