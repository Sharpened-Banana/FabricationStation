local P2 = require("tests.helpers.phase2")
describe("Customers store", function()
  local ns, C
  before_each(function()
    ns = P2.boot(); P2.load(ns, {"Modules/Customers.lua"}); C = ns.FS:GetModule("Customers")
  end)
  it("normalizes names to Name-Realm", function()
    assert.equal("Bob-Silvermoon", C:NormalizeName("Bob"))
    assert.equal("Bob-Area52", C:NormalizeName("Bob-Area52"))
    assert.is_nil(C:NormalizeName(nil)); assert.is_nil(C:NormalizeName(""))
  end)
  it("adds the phase-2 bus names", function()
    assert.equal("FS_ORDER_FULFILLED", ns.Msg.ORDER_FULFILLED)
    assert.equal("FS_PERSONAL_ORDER_ARRIVED", ns.Msg.PERSONAL_ORDER_ARRIVED)
    assert.equal("Me-Silvermoon", ns.FS:CharKey()); assert.equal(1000, ns.FS:Now())
  end)
  it("records a fulfilled order once and totals tips", function()
    spy.on(C, "SendMessage")
    local row = {time=1000, orderID=777, itemID=211111, recipeID=4444, quality=3, tip=500000, commission=450000, orderType="personal"}
    C:RecordOrder("Bob-Silvermoon", row); C:RecordOrder("Bob-Silvermoon", row)
    local r = C:Get("Bob-Silvermoon")
    assert.equal(1, #r.orders); assert.equal(500000, r.tipsTotal)
    assert.equal(1000, r.firstSeen); assert.equal(1000, r.lastSeen); assert.equal("", r.notes)
    assert.spy(C.SendMessage).was.called_with(C, "FS_CUSTOMERS_CHANGED", "Bob-Silvermoon")
  end)
  it("captures player orders on FS_ORDER_FULFILLED and skips NPC orders", function()
    local f = {orderID=1, orderType="public", customer="Ann-Silvermoon", recipeID=4444, itemID=211111, quality=2, tip=100000, consortiumCut=10000, commission=90000, rewards={}, rewardsValue=0, time=1000, charKey="Me-Silvermoon"}
    C:OnOrderFulfilled("FS_ORDER_FULFILLED", f)
    C:OnOrderFulfilled("FS_ORDER_FULFILLED", P2.merge(f, {orderID=2, orderType="npc", customer=nil, npcCreatureID=9}))
    assert.equal(1, #C:Get("Ann-Silvermoon").orders)
    assert.is_nil(C:Get(nil))
  end)

  describe("details", function()
    local function row(over) return P2.merge({time=1000, orderID=1, itemID=2, recipeID=3, quality=1, tip=100, commission=90, orderType="public"}, over) end
    it("trims names and uses the CharKey realm for bare names", function()
      assert.equal("Bob-Silvermoon", C:NormalizeName("  Bob "))
      assert.is_nil(C:NormalizeName("   ")); assert.is_nil(C:NormalizeName(42))
    end)
    it("keeps orders unique per orderID, sums tips and moves lastSeen forward only", function()
      C:RecordOrder("Bob", row({orderID=1, time=1000, tip=100}))
      C:RecordOrder("Bob", row({orderID=2, time=2000, tip=250}))
      C:RecordOrder("Bob", row({orderID=3, time=500, tip=1}))
      local r = C:Get("Bob-Silvermoon")
      assert.equal(3, #r.orders); assert.equal(351, r.tipsTotal)
      assert.equal(1000, r.firstSeen); assert.equal(2000, r.lastSeen)
      assert.same({time=2000, orderID=2, itemID=2, recipeID=3, quality=1, tip=250, commission=90, orderType="public"}, r.orders[2])
      assert.same({}, r.tags); assert.equal("Bob-Silvermoon", r.nameRealm)
    end)
    it("sends FS_CUSTOMERS_CHANGED only when something changed", function()
      spy.on(C, "SendMessage")
      C:RecordOrder("Bob", row()); C:RecordOrder("Bob", row())
      assert.spy(C.SendMessage).was.called(1)
    end)
    it("ignores a missing name or row", function()
      assert.is_nil(C:RecordOrder(nil, row())); assert.is_nil(C:RecordOrder("Bob", nil))
      assert.same({}, ns.FS.db.global.customers)
    end)
    it("fills the missing parts of a damaged saved record without wiping it", function()
      ns.FS.db.global.customers["Bob-Silvermoon"] = {notes = "VIP", tags = {friend = true}, tipsTotal = 7}
      C:RecordOrder("Bob-Silvermoon", row({tip=3}))
      local r = C:Get("Bob-Silvermoon")
      assert.equal("VIP", r.notes); assert.is_true(r.tags.friend)
      assert.equal(10, r.tipsTotal); assert.equal(1, #r.orders); assert.equal(1000, r.firstSeen)
    end)
    it("writes nothing while the saved data is from a newer version", function()
      ns.FS.dbIsNewer = true
      spy.on(C, "SendMessage")
      assert.is_nil(C:RecordOrder("Bob", row()))
      assert.same({}, ns.FS.db.global.customers)
      assert.spy(C.SendMessage).was_not.called()
      ns.FS.dbIsNewer = nil
      C:RecordOrder("Bob", row()); ns.FS.dbIsNewer = true
      assert.is_table(C:RecordOrder("Bob", row({orderID=9})))   -- the saved record, unchanged
      assert.equal(1, #C:Get("Bob-Silvermoon").orders)
    end)
    it("reads fine without a database", function()
      ns.FS.db = nil
      assert.is_nil(C:Get("Bob-Silvermoon")); assert.is_nil(C:RecordOrder("Bob", row()))
    end)
  end)

  describe("bus wiring", function()
    it("records an order sent on FS_ORDER_FULFILLED", function()
      ns.FS:SendMessage(ns.Msg.ORDER_FULFILLED, {orderID=5, orderType="guild", customer="Cy", recipeID=1, itemID=2, quality=1,
        tip=10, consortiumCut=1, commission=9, rewards={}, rewardsValue=0, time=1000, charKey="Me-Silvermoon"})
      local r = C:Get("Cy-Silvermoon")
      assert.equal(1, #r.orders); assert.equal("guild", r.orders[1].orderType); assert.equal(9, r.orders[1].commission)
    end)
    it("stops listening when turned off", function()
      C:Disable()
      ns.FS:SendMessage(ns.Msg.ORDER_FULFILLED, {orderID=5, orderType="guild", customer="Cy", tip=10, time=1000})
      assert.is_nil(C:Get("Cy-Silvermoon"))
    end)
    it("is a user-toggleable module", function() assert.is_falsy(C.coreModule) end)
    it("stops itself on a handler error and logs it", function()
      C.RecordOrder = function() error("boom") end
      ns.FS:SendMessage(ns.Msg.ORDER_FULFILLED, {orderID=5, orderType="guild", customer="Cy", tip=10, time=1000})
      assert.is_false(C:IsEnabled())
      assert.equal("Customers", ns.FS.db.global.diagnostics.errors[1].source)
    end)
  end)
end)
