describe("GameData", function()
  local ns
  before_each(function()
    install_wow_stubs()
    ns = load_addon({}, "Data/GameData.lua")
  end)

  it("stores and returns tables", function() ns.GameData.Define("A", 70575, { x = 1 }); assert.equals(1, ns.GameData.Get("A").x) end)
  it("returns nil for an unknown table", function() assert.is_nil(ns.GameData.Get("Nope")) end)
  it("reports current data", function()
    ns.GameData.Define("A", 70575, {}); local s = ns.GameData.Status(70575)
    assert.equals(70575, s.build); assert.is_false(s.outdated); assert.is_false(s.missing)
  end)
  it("reports outdated data", function() ns.GameData.Define("A", 70575, {}); assert.is_true(ns.GameData.Status(70600).outdated) end)
  it("reports missing data when nothing or an ungenerated table is defined", function()
    assert.is_true(ns.GameData.Status(70575).missing)
    ns.GameData.Define("A", nil, {}); assert.is_true(ns.GameData.Status(70575).missing)
  end)
  it("keeps an ungenerated table readable", function()
    ns.GameData.Define("A", nil, { x = 2 }); assert.equals(2, ns.GameData.Get("A").x)
  end)
  it("lists tables built for a different build", function()
    ns.GameData.Define("A", 70575, {}); ns.GameData.Define("B", 70575, {}); ns.GameData.Define("C", 70529, {})
    assert.same({ "C" }, ns.GameData.Status(70575).mismatched)
  end)
  it("Build is the shared build, or the most common one", function()
    assert.is_nil(ns.GameData.Build())
    ns.GameData.Define("A", 70529, {}); assert.equals(70529, ns.GameData.Build())
    ns.GameData.Define("B", 70575, {}); ns.GameData.Define("C", 70575, {})
    assert.equals(70575, ns.GameData.Build())
  end)
  it("Build breaks ties toward the newest build and ignores ungenerated tables", function()
    ns.GameData.Define("A", 70529, {}); ns.GameData.Define("B", 70575, {}); ns.GameData.Define("C", nil, {})
    assert.equals(70575, ns.GameData.Build())
  end)
  it("redefining a table replaces it", function()
    ns.GameData.Define("A", 70529, { x = 1 }); ns.GameData.Define("A", 70575, { x = 2 })
    assert.equals(2, ns.GameData.Get("A").x); assert.equals(70575, ns.GameData.Build())
  end)
  it("rejects bad arguments", function()
    assert.has_error(function() ns.GameData.Define(nil, 1, {}) end)
    assert.has_error(function() ns.GameData.Define("A", 1, nil) end)
    assert.has_error(function() ns.GameData.Define("A", "70575", {}) end)
  end)
end)
