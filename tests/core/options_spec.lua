describe("Options and module toggles", function()
  local W, ns
  before_each(function()
    W = install_wow_stubs()
    ns = load_addon({}, "Core/DB.lua")
  end)

  it("builds the root options group", function()
    local t = ns.FS:GetOptionsTable()
    assert.equals("group", t.type); assert.equals("FabricationStation", t.name)
    assert.equals("tab", t.childGroups); assert.is_table(t.args)
  end)
  it("adds registered groups to the options table", function()
    local g = { type = "group", name = "Prices", args = {} }; ns.FS:RegisterOptions("prices", g)
    assert.equals(g, ns.FS:GetOptionsTable().args.prices)
  end)
  it("registers with AceConfig on init and notifies on later registration", function()
    W.boot(); assert.is_truthy(W.config.registered.FabricationStation)
    local before = W.config.notified; ns.FS:RegisterOptions("x", { type = "group", name = "X", args = {} })
    assert.equals(before + 1, W.config.notified)
  end)
  it("does not notify for registrations made before init", function()
    ns.FS:RegisterOptions("x", { type = "group", name = "X", args = {} }); assert.equals(0, W.config.notified)
  end)
  it("serves a fresh table to AceConfig each time it asks", function()
    W.boot()
    local provider = W.config.registered.FabricationStation
    ns.FS:RegisterOptions("late", { type = "group", name = "Late", args = {} })
    assert.is_truthy(provider("dialog", "AceConfigDialog-3.0").args.late)
  end)
  it("honours stored module toggles at init", function()
    local M = ns.FS:NewModule("Dummy", "AceEvent-3.0")
    _G.FabricationStationDB = { global = { settings = { modules = { Dummy = false } } } }
    W.boot(); assert.is_false(M:IsEnabled())
    ns.FS:SetModuleEnabled("Dummy", true); assert.is_true(M:IsEnabled())
    assert.is_true(ns.FS.db.global.settings.modules.Dummy)
  end)
  it("leaves modules enabled unless explicitly set to false", function()
    local M = ns.FS:NewModule("Dummy", "AceEvent-3.0"); W.boot(); assert.is_true(M:IsEnabled())
  end)
  it("disables a module now and stores false", function()
    local M = ns.FS:NewModule("Dummy", "AceEvent-3.0"); W.boot()
    ns.FS:SetModuleEnabled("Dummy", false)
    assert.is_false(M:IsEnabled()); assert.is_false(ns.FS.db.global.settings.modules.Dummy)
  end)
  it("clears failedModules on enable only", function()
    local M = ns.FS:NewModule("Dummy", "AceEvent-3.0"); W.boot()
    ns.FS.failedModules.Dummy = "err"
    ns.FS:SetModuleEnabled("Dummy", false); assert.equals("err", ns.FS.failedModules.Dummy)
    ns.FS:SetModuleEnabled("Dummy", true); assert.is_nil(ns.FS.failedModules.Dummy); assert.is_true(M:IsEnabled())
  end)
  it("ignores unknown modules and refuses core modules", function()
    local C = ns.FS:NewModule("CoreThing", "AceEvent-3.0"); C.coreModule = true; W.boot()
    assert.is_false(ns.FS:SetModuleEnabled("Nope", false))
    assert.is_false(ns.FS:SetModuleEnabled("CoreThing", false))
    assert.is_true(C:IsEnabled()); assert.is_nil(ns.FS.db.global.settings.modules.CoreThing)
  end)
  it("never applies a stored false to a core module", function()
    local C = ns.FS:NewModule("CoreThing", "AceEvent-3.0"); C.coreModule = true
    _G.FabricationStationDB = { global = { settings = { modules = { CoreThing = false } } } }
    W.boot(); assert.is_true(C:IsEnabled())
  end)
  it("lists only non-core modules in the modules group", function()
    ns.FS:NewModule("Dummy", "AceEvent-3.0"); local C = ns.FS:NewModule("CoreThing", "AceEvent-3.0"); C.coreModule = true
    W.boot(); local args = ns.FS:GetOptionsTable().args.modules.args
    assert.is_truthy(args.Dummy); assert.is_nil(args.CoreThing)
    assert.equals(90, ns.FS:GetOptionsTable().args.modules.order)
  end)
  it("includes modules created after init", function()
    W.boot(); ns.FS:NewModule("Late", "AceEvent-3.0")
    assert.is_truthy(ns.FS:GetOptionsTable().args.modules.args.Late)
  end)
  it("toggle get/set drive the module and the stored flag", function()
    local M = ns.FS:NewModule("Dummy", "AceEvent-3.0"); W.boot()
    local t = ns.FS:GetOptionsTable().args.modules.args.Dummy
    assert.equals("toggle", t.type); assert.is_true(t.get())
    t.set(nil, false); assert.is_false(M:IsEnabled()); assert.is_false(t.get())
    assert.is_false(ns.FS.db.global.settings.modules.Dummy)
  end)
  it("suffixes the toggle name for a failed module", function()
    ns.FS:NewModule("Dummy", "AceEvent-3.0"); W.boot()
    assert.equals("Dummy", ns.FS:GetOptionsTable().args.modules.args.Dummy.name)
    ns.FS:SafeCall("Dummy", function() error("x") end)
    assert.equals("Dummy (stopped after an error)", ns.FS:GetOptionsTable().args.modules.args.Dummy.name)
    ns.FS:SetModuleEnabled("Dummy", true)
    assert.equals("Dummy", ns.FS:GetOptionsTable().args.modules.args.Dummy.name)
  end)
end)
