describe("Core", function()
  local W, ns
  before_each(function()
    W = install_wow_stubs()
    ns = load_addon({}, "Core/DB.lua")
  end)

  it("builds CharKey from the normalized realm", function() assert.equals("Thrall-ArgentDawn", ns.FS:CharKey()) end)
  it("falls back to GetRealmName without spaces or hyphens", function()
    _G.GetNormalizedRealmName = function() return nil end; _G.GetRealmName = function() return "Azjol-Nerub" end
    assert.equals("Thrall-AzjolNerub", ns.FS:CharKey())
  end)
  it("Now returns server time", function() W.now = 1234; assert.equals(1234, ns.FS:Now()) end)

  describe("SafeCall", function()
    it("returns results on success", function()
      assert.same({ true, 1, 2 }, { ns.FS:SafeCall("Core", function(a, b) return a, b end, 1, 2) })
    end)
    it("disables the failing module, logs and notifies once", function()
      local M = ns.FS:NewModule("Boom", "AceEvent-3.0"); W.boot()
      local ok, err = ns.FS:SafeCall("Boom", function() error("boom") end)
      ns.FS:SafeCall("Boom", function() error("again") end)
      assert.is_false(ok); assert.matches("boom", err); assert.is_false(M:IsEnabled())
      assert.equals("FS_MODULE_FAILED", W.messages[1][1]); assert.equals("Boom", W.messages[1][2])
      assert.equals(2, #ns.FS.db.global.diagnostics.errors); assert.equals(1, #W.printed)
      assert.equals(1, #W.messages)
      assert.is_truthy(ns.FS.failedModules.Boom)
    end)
    it("notifies again after the module is re-enabled and fails again, with no second chat line", function()
      local M = ns.FS:NewModule("Boom", "AceEvent-3.0"); W.boot()
      ns.FS:SafeCall("Boom", function() error("first") end)
      ns.FS:SetModuleEnabled("Boom", true)
      assert.is_true(M:IsEnabled()); assert.is_nil(ns.FS.failedModules.Boom)
      local ok, err = ns.FS:SafeCall("Boom", function() error("second") end)
      assert.is_false(ok); assert.is_false(M:IsEnabled())
      assert.equals(2, #W.messages); assert.equals("FS_MODULE_FAILED", W.messages[2][1])
      assert.equals("Boom", W.messages[2][2]); assert.equals(err, W.messages[2][3])
      assert.equals(err, ns.FS.failedModules.Boom)
      assert.equals(1, #W.printed)  -- the chat line is once per module per session
    end)
    it("still records, notifies and returns false when OnDisable errors", function()
      local M = ns.FS:NewModule("Boom", "AceEvent-3.0")
      function M:OnDisable() error("disable failed") end
      W.boot()
      local ok, err
      assert.has_no.errors(function() ok, err = ns.FS:SafeCall("Boom", function() error("boom") end) end)
      assert.is_false(ok); assert.matches("boom", err)
      assert.equals(err, ns.FS.failedModules.Boom)
      assert.equals(1, #W.messages); assert.equals("FS_MODULE_FAILED", W.messages[1][1])
      assert.equals(1, #W.printed)
      local errs = ns.FS.db.global.diagnostics.errors
      assert.equals("Boom", errs[1].source); assert.matches("boom", errs[1].err)
      assert.equals("Boom", errs[2].source); assert.matches("disable failed", errs[2].err)
    end)
    it("prints the documented message and sends the error text", function()
      ns.FS:NewModule("Boom", "AceEvent-3.0"); W.boot()
      local _, err = ns.FS:SafeCall("Boom", function() error("boom") end)
      assert.equals("FabricationStation: Boom stopped after an error and was turned off. See /fs settings > Diagnostics.",
        W.printed[1])
      assert.equals(err, W.messages[1][3]); assert.equals(err, ns.FS.failedModules.Boom)
    end)
    it("with a non-module source only logs", function()
      local ok = ns.FS:SafeCall("Tab:x", function() error("x") end); assert.is_false(ok); assert.equals(0, #W.messages)
      assert.equals("Tab:x", ns.FS.pendingErrors[1].source)
    end)
    it("passes nil arguments through and keeps nil results", function()
      assert.same({ true, nil, nil, 2, n = 4 }, (function(...) return { n = select("#", ...), ... } end)(
        ns.FS:SafeCall("Core", function(a, b, c) return a, b, c end, nil, nil, 2)))
    end)
    it("records time, source, error and a stack in the log entry", function()
      W.now = 555; ns.FS:SafeCall("Tab:x", function() error("x", 0) end)
      local e = ns.FS.pendingErrors[1]
      assert.equals(555, e.time); assert.equals("Tab:x", e.source); assert.equals("x", e.err)
      assert.is_string(e.stack)
    end)
    it("stringifies non-string errors", function()
      local ok, err = ns.FS:SafeCall("Tab:x", function() error({}, 0) end)
      assert.is_false(ok); assert.is_string(err)
    end)
  end)

  describe("LogError", function()
    it("caps the pending buffer at 50, dropping the oldest", function()
      for i = 1, 55 do ns.FS:LogError("S", "e" .. i) end
      assert.equals(50, #ns.FS.pendingErrors); assert.equals("e6", ns.FS.pendingErrors[1].err)
      assert.equals("e55", ns.FS.pendingErrors[50].err)
    end)
    it("writes to db.global.diagnostics.errors once a DB exists, capped at 50", function()
      ns.FS.db = { global = { diagnostics = { errors = {} } } }
      for i = 1, 52 do ns.FS:LogError("S", "e" .. i) end
      local errs = ns.FS.db.global.diagnostics.errors
      assert.equals(50, #errs); assert.equals("e3", errs[1].err); assert.equals(0, #ns.FS.pendingErrors)
    end)
  end)

  describe("Wrap", function()
    it("returns a function that runs through SafeCall", function()
      local f = ns.FS:Wrap("Tab:x", function(a) return a * 2 end)
      assert.same({ true, 6 }, { f(3) })
      local g = ns.FS:Wrap("Tab:x", function() error("bad") end)
      assert.is_false((g())); assert.equals(1, #ns.FS.pendingErrors)
    end)
  end)

  it("starts with empty failedModules", function() assert.same({}, ns.FS.failedModules) end)

  it("Debounce runs only the last fn after the quiet period", function()
    local calls = {}
    ns.FS:Debounce("k", 1, function() table.insert(calls, 1) end); W.advance(0.3)
    ns.FS:Debounce("k", 1, function() table.insert(calls, 2) end); W.advance(0.3)
    ns.FS:Debounce("k", 1, function() table.insert(calls, 3) end)
    W.advance(0.9); assert.same({}, calls); W.advance(0.2); assert.same({ 3 }, calls)
  end)
  it("Debounce keys are independent and re-arm after firing", function()
    local calls = {}
    ns.FS:Debounce("a", 1, function() table.insert(calls, "a1") end)
    ns.FS:Debounce("b", 1, function() table.insert(calls, "b1") end)
    W.advance(1.1); assert.same({ "a1", "b1" }, calls)
    ns.FS:Debounce("a", 1, function() table.insert(calls, "a2") end); W.advance(1.1)
    assert.same({ "a1", "b1", "a2" }, calls)
  end)

  describe("slash", function()
    it("registers fs and fabstation on boot", function()
      W.boot(); assert.is_function(W.slash.fs); assert.is_function(W.slash.fabstation)
      local got; ns.FS:RegisterSlash("capture", function(rest) got = rest end, "save fixture")
      W.slash.fabstation("capture 9"); assert.equals("9", got)
    end)
    it("dispatches by first word, case-insensitively", function()
      local got; ns.FS:RegisterSlash("capture", function(rest) got = rest end, "save fixture")
      ns.FS:HandleSlash("CAPTURE 123"); assert.equals("123", got)
    end)
    it("passes an empty string when there are no arguments", function()
      local got; ns.FS:RegisterSlash("capture", function(rest) got = rest end, "x")
      ns.FS:HandleSlash("  capture  "); assert.equals("", got)
    end)
    it("dispatches the bare /fs to the empty-name handler", function()
      local hit; ns.FS:RegisterSlash("", function() hit = true end, "open window")
      ns.FS:HandleSlash(""); assert.is_true(hit)
      hit = nil; ns.FS:HandleSlash(nil); assert.is_true(hit)
    end)
    it("prints help for unknown commands", function()
      ns.FS:RegisterSlash("capture", function() end, "save fixture"); ns.FS:HandleSlash("zzz")
      assert.matches("/fs capture %- save fixture", table.concat(W.printed, "\n"))
    end)
    it("prints sorted help for help, including the bare command", function()
      ns.FS:RegisterSlash("zeta", function() end, "last")
      ns.FS:RegisterSlash("alpha", function() end, "first")
      ns.FS:RegisterSlash("", function() end, "open window")
      ns.FS:HandleSlash("help")
      assert.same({ "/fs - open window", "/fs alpha - first", "/fs zeta - last" }, W.printed)
    end)
    it("isolates handler errors and logs them", function()
      ns.FS:RegisterSlash("bad", function() error("kaboom") end, "x")
      assert.has_no.errors(function() ns.FS:HandleSlash("bad") end)
      assert.equals("Slash:bad", ns.FS.pendingErrors[1].source)
    end)
  end)
end)
