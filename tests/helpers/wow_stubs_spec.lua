  describe("clock", function()
    it("drives time() and GetServerTime() from W.now", function()
      assert.equals(1700000000, W.now); assert.equals(1700000000, time()); assert.equals(1700000000, GetServerTime())
      W.advance(5); assert.equals(1700000005, GetServerTime())
      W.now = 42; assert.equals(42, time())
      W.advance(0.5); assert.equals(W.now, GetServerTime()); assert.equals(W.now, time())
    end)
    it("runs timers scheduled during advance, including nested ones, in due order", function()
      local order = {}
      C_Timer.After(1, function()
        order[#order + 1] = "a"
        C_Timer.After(1, function() order[#order + 1] = "c" end)
      end)
      C_Timer.After(1.5, function() order[#order + 1] = "b" end)
      W.advance(10)
      assert.same({ "a", "b", "c" }, order); assert.equals(1700000010, W.now)
    end)
    it("treats each advance as a frame: a zero-delay timer scheduled during advance waits for the next one", function()
      local n = 0
      local function tick() n = n + 1; if n < 3 then C_Timer.After(0, tick) end end
      C_Timer.After(0, tick)
      W.advance(0); assert.equals(1, n)
      W.advance(0); assert.equals(2, n)
      W.advance(5); assert.equals(3, n)
      local hit = false; C_Timer.After(1, function() C_Timer.NewTimer(0, function() hit = true end) end)
      W.advance(1); assert.is_false(hit); W.advance(0); assert.is_true(hit)
    end)
    it("runs a zero-delay timer created mid-way through a longer advance within that advance", function()
      local hit = false
      C_Timer.After(5, function() C_Timer.After(0, function() hit = true end) end)
      W.advance(10); assert.is_true(hit); assert.equals(1700000010, W.now)
    end)
    it("sees the due time as the current time inside a callback", function()
      local seen
      C_Timer.After(3, function() seen = GetServerTime() end)
      W.advance(10); assert.equals(1700000003, seen)
    end)
    it("runs NewTicker repeatedly and stops on Cancel or iteration limit", function()
      local n = 0; local tk = C_Timer.NewTicker(1, function() n = n + 1 end)
      W.advance(3); assert.equals(3, n)
