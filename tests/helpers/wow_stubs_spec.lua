  describe("AceAddon", function()
    it("boots OnInitialize then OnEnable in creation order, skipping disabled modules", function()
      local log = {}
      local A = LibStub("AceAddon-3.0"):NewAddon("T", "AceEvent-3.0")
      local function track(o, name)
        o.OnInitialize = function() log[#log + 1] = "init " .. name end
        o.OnEnable = function() log[#log + 1] = "enable " .. name end
      end
      track(A, "A")
      local M1 = A:NewModule("M1"); track(M1, "M1")
      local M2 = A:NewModule("M2"); track(M2, "M2"); M2:SetEnabledState(false)
      local M3 = A:NewModule("M3"); track(M3, "M3")
      W.boot()
      assert.same({ "init A", "init M1", "init M2", "init M3", "enable A", "enable M1", "enable M3" }, log)
