local P2 = require("tests.helpers.phase2")

describe("phase-2 helpers", function()
  describe("P2.merge", function()
    it("deep-merges into a new table, b wins, without touching the arguments", function()
      local a = { x = { y = 1, z = 2 }, k = 1 }
      local b = { x = { y = 9 }, n = { m = 1 } }
      local out = P2.merge(a, b)
      assert.same({ x = { y = 9, z = 2 }, k = 1, n = { m = 1 } }, out)
      assert.same({ x = { y = 1, z = 2 }, k = 1 }, a); assert.equal(b.n, out.n)
    end)
    it("replaces non-table values and removes keys set to P2.NIL", function()
      assert.same({ k = 2 }, P2.merge({ k = 1, g = 3 }, { k = 2, g = P2.NIL }))
      local fn = function() end
      assert.equal(fn, P2.merge({ f = 1 }, { f = fn }).f)
    end)
  end)

  describe("P2.raw_order", function()
    it("has the verified defaults and applies overrides", function()
      local o = P2.raw_order()
      assert.same({ orderID = 777, itemID = 211111, spellID = 4444, skillLineAbilityID = 55, orderType = 2, orderState = 2,
        expirationTime = 8600, claimEndTime = 0, minQuality = 0, tipAmount = 500000, consortiumCut = 50000,
        isRecraft = false, isFulfillable = true, reagentState = 0, customerName = "Bob", customerNotes = "",
        reagents = {}, npcOrderRewards = {}, npcCraftingOrderSetID = 0, npcTreasureID = 0 }, o)
      assert.equal(3, P2.raw_order({ orderType = 3 }).orderType)
      assert.is_nil(P2.raw_order({ customerName = P2.NIL }).customerName)
      P2.raw_order().reagents[1] = "x"; assert.same({}, P2.raw_order().reagents)
    end)
  end)

  describe("P2.boot / P2.load / P2.fake_module", function()
    it("builds a world with phase-2 globals that is not booted yet", function()
      local ns, W = P2.boot()
      assert.equal(1000, W.now); assert.equal(1000, ns.FS:Now()); assert.equal("Me-Silvermoon", ns.FS:CharKey())
      assert.equal(2, Enum.CraftingOrderType.Personal); assert.equal(3, Enum.CraftingOrderType.Npc)
      assert.equal(1, Enum.CraftingOrderReagentSource.Customer); assert.equal(2, Enum.CraftingOrderReagentsType.None)
      assert.equal(6, Enum.CraftingOrderResult.CannotClaim)
      assert.equal(1, Enum.BagIndex.Bag_1)   -- merged into the shared Enum, not replacing it
      assert.is_function(ns.UI.FormatMoney); assert.is_nil(ns.FS.db)
      assert.is_nil(ns.FS:GetModule("Customers", true))
      assert.equal("--", ns.UI.FormatMoney(nil))
    end)
    it("applies stub overrides on top of the phase-2 globals", function()
      local ns = P2.boot({ UnitName = function() return "Zed" end, Enum = { CraftingOrderType = { Npc = 9 } } })
      assert.equal("Zed-Silvermoon", ns.FS:CharKey()); assert.equal(9, Enum.CraftingOrderType.Npc)
      assert.equal(2, Enum.CraftingOrderType.Personal)
      assert.equal("Me", P2.GLOBALS.UnitName())
    end)
    it("boots once on the first load, with fake modules created before it", function()
      local ns = P2.boot()
      local enabled = 0
      local fake = P2.fake_module(ns, "Prices", { Get = function() return "p" end, OnEnable = function() enabled = enabled + 1 end })
      P2.load(ns, {})
      assert.is_table(ns.FS.db); assert.equal(1, enabled); assert.equal("p", ns.FS:GetModule("Prices"):Get())
      assert.equal(fake, ns.FS:GetModule("Prices"))
      P2.load(ns, {}); assert.equal(1, enabled)
    end)
    it("resets between boots", function()
      local ns1 = P2.boot(); P2.load(ns1, {})
      ns1.FS.db.global.marker = true
      local ns2 = P2.boot(); P2.load(ns2, {})
      assert.is_nil(ns2.FS.db.global.marker); assert.are_not.equal(ns1, ns2)
    end)
    it("refuses a ns that did not come from boot", function()
      P2.boot()
      assert.has_error(function() P2.load({}, {}) end)
    end)
  end)
end)
