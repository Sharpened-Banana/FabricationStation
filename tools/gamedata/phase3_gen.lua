-- Phase-3 GameData generator library: hand-authored knowledge CSVs + wago.tools DB2 CSV rows ->
-- the Knowledge and RecipeSources tables, a quest cross-check, and 1a's data-file format.
-- Plain Lua 5.1, run outside the game (no WoW globals). The CLI is tools/gamedata/gen_phase3.lua.
--
-- Rows are tables { [column] = string } as tools/lib/csv.lua returns them. Errors are plain strings
-- (level 0) naming the row, so the CLI can prefix the file name.
local source = debug.getinfo(1, "S").source
local dir = source:match("^@(.*)[/\\][^/\\]*$") or "."
package.path = dir .. "/../lib/?.lua;tools/lib/?.lua;" .. package.path

local csv = require("csv")
local serialize = require("serialize")

local G = {}

-- Points per first craft of a recipe (Midnight; from the plan, unverified in game).
G.FIRST_CRAFT_POINTS = 1

-- knowledge_sources.csv category -> reset rule.
G.RESET = {
  weeklyQuest = "weekly", treatise = "weekly", treasure = "weekly", drop = "weekly",
  darkmoon = "monthly",
  unique = "once",
}

-- DB2 SpellEffect.Effect codes (unverified against the Midnight client; see tools/gamedata/README.md).
G.EFFECT_LEARN_SPELL = 36
G.EFFECT_QUEST_COMPLETE = 16

G.HEADER = "-- GENERATED by tools/gamedata/gen_phase3.lua from wago.tools DB2 CSV, build %s. Do not edit."
G.EMPTY_HEADER = "-- GENERATED by tools/gamedata/gen_phase3.lua --empty (wago.tools unavailable): Knowledge from "
  .. "hand-authored CSVs (unverified); RecipeSources not generated. Do not edit."

-- A positive integer from a CSV string, else nil.
local function posInt(s)
  if type(s) ~= "string" or not s:match("^%d+$") then return nil end
  local n = tonumber(s)
  if n < 1 then return nil end
  return n
end

-- An optional column: nil when absent or empty.
local function opt(row, name)
  local v = row[name]
  if v == nil or v == "" then return nil end
  return v
end

-- csv.col with the row named in the error.
local function col(where, row, name, index)
  local ok, v = pcall(csv.col, row, name, index)
  if not ok then error(where .. ": " .. v, 0) end
  return v
end

-- A numeric DB2 column; errors with the table, row and column when it is not a number.
local function num(tableName, i, row, name, index)
  local where = tableName .. " row " .. i
  local v = col(where, row, name, index)
  local n = tonumber(v)
  if n == nil then
    local label = index ~= nil and (name .. "[" .. index .. "]") or name
    error(where .. ": " .. label .. " is not a number: '" .. v .. "'", 0)
  end
  return n
end

-- skill_lines.csv rows -> { [skillLineID] = { base, name } }.
local function parseVariants(rows)
  local variants = {}
  for i, row in ipairs(rows) do
    local where = "skill_lines row " .. i
    local idText = col(where, row, "skillLineID")
    local id = posInt(idText)
    if not id then error(where .. ": bad skillLineID '" .. idText .. "'", 0) end
    local baseText = col(where, row, "base")
    local base = posInt(baseText)
    if not base then error(where .. ": bad base '" .. baseText .. "'", 0) end
    local name = col(where, row, "name")
    if name == "" then error(where .. ": no name", 0) end
    if variants[id] then error(where .. ": duplicate skillLineID " .. id, 0) end
    variants[id] = { base = base, name = name }
  end
  return variants
end

local function optionalPosInt(where, row, name)
  local text = opt(row, name)
  if text == nil then return nil end
  local n = posInt(text)
  if not n then error(where .. ": bad " .. name .. " '" .. text .. "'", 0) end
  return n
end

-- skill_lines.csv rows + knowledge_sources.csv rows -> the Knowledge table.
function G.buildKnowledge(skillLineRows, sourceRows)
  local variants = parseVariants(skillLineRows)
  local sources, seen = {}, {}
  for i, row in ipairs(sourceRows) do
    local where = "row " .. i
    local lineText = col(where, row, "skillLineID")
    local skillLineID = posInt(lineText)
    if not skillLineID or not variants[skillLineID] then error(where .. ": unknown skillLineID " .. lineText, 0) end
    local category = col(where, row, "category")
    local reset = G.RESET[category]
    if not reset then error(where .. ": unknown category '" .. category .. "'", 0) end
    local quests = {}
    for word in col(where, row, "quests"):gmatch("%S+") do
      local q = posInt(word)
      if not q then error(where .. ": bad quest ID '" .. word .. "'", 0) end
      quests[#quests + 1] = q
    end
    if #quests == 0 then error(where .. ": no quests", 0) end
    local limit = optionalPosInt(where, row, "limit")
    local itemID = optionalPosInt(where, row, "itemID")
    local pointsText = col(where, row, "points")
    local points = posInt(pointsText)
    if not points then error(where .. ": bad points '" .. pointsText .. "'", 0) end
    local id = skillLineID .. ":" .. category .. ":" .. quests[1]
    if seen[id] then error(where .. ": duplicate id " .. id, 0) end
    seen[id] = true
    sources[#sources + 1] = {
      id = id, skillLineID = skillLineID, category = category, reset = reset, quests = quests,
      limit = limit, itemID = itemID, points = points, hint = opt(row, "hint"),
    }
  end
  table.sort(sources, function(a, b)
    if a.skillLineID ~= b.skillLineID then return a.skillLineID < b.skillLineID end
    if a.category ~= b.category then return a.category < b.category end
    return a.id < b.id
  end)
  return { firstCraftPoints = G.FIRST_CRAFT_POINTS, variants = variants, sources = sources }
end

-- ItemEffect + ItemXItemEffect -> list of { spell, item } (the spell an item casts on use).
local function itemSpellPairs(itemEffect, itemXEffect)
  local spellOfEffect = {}
  for i, row in ipairs(itemEffect) do
    spellOfEffect[num("ItemEffect", i, row, "ID")] = num("ItemEffect", i, row, "SpellID")
  end
  local pairsList = {}
  for i, row in ipairs(itemXEffect) do
    local spell = spellOfEffect[num("ItemXItemEffect", i, row, "ItemEffectID")]
    if spell then pairsList[#pairsList + 1] = { spell = spell, item = num("ItemXItemEffect", i, row, "ItemID") } end
  end
  return pairsList
end

local RANK = { unknown = 1, auto = 2, item = 3 }

-- skill_lines.csv rows + SkillLineAbility, SpellEffect, ItemEffect, ItemXItemEffect rows -> the RecipeSources table.
-- A recipe is "item" when an item's on-use spell teaches it (SpellEffect LEARN_SPELL; lowest itemID wins),
-- else "auto" when SkillLineAbility.AcquireMethod ~= 0, else "unknown".
function G.buildRecipeSources(skillLineRows, sla, spellEffect, itemEffect, itemXEffect)
  local variants = parseVariants(skillLineRows)
  local minItemOfSpell = {}
  for _, p in ipairs(itemSpellPairs(itemEffect, itemXEffect)) do
    local cur = minItemOfSpell[p.spell]
    if cur == nil or p.item < cur then minItemOfSpell[p.spell] = p.item end
  end
  local teachItem = {}
  for i, row in ipairs(spellEffect) do
    if num("SpellEffect", i, row, "Effect") == G.EFFECT_LEARN_SPELL then
      local item = minItemOfSpell[num("SpellEffect", i, row, "SpellID")]
      if item then
        local recipe = num("SpellEffect", i, row, "EffectTriggerSpell")
        if teachItem[recipe] == nil or item < teachItem[recipe] then teachItem[recipe] = item end
      end
    end
  end

  local bySkillLine = {}
  for line in pairs(variants) do bySkillLine[line] = {} end
  for i, row in ipairs(sla) do
    local recipes = bySkillLine[num("SkillLineAbility", i, row, "SkillLine")]
    if recipes then
      local spell = num("SkillLineAbility", i, row, "Spell")
      local entry
      if teachItem[spell] then
        entry = { kind = "item", itemID = teachItem[spell] }
      elseif num("SkillLineAbility", i, row, "AcquireMethod") ~= 0 then
        entry = { kind = "auto" }
      else
        entry = { kind = "unknown" }
      end
      local cur = recipes[spell]
      if cur == nil or RANK[entry.kind] > RANK[cur.kind] then recipes[spell] = entry end
    end
  end
  return { bySkillLine = bySkillLine }
end

-- Compares each source's quests with the quests its item completes (SpellEffect QUEST_COMPLETE,
-- EffectMiscValue[0], through the item's on-use spells). Returns warning strings in source order.
function G.crossCheck(knowledge, spellEffect, itemEffect, itemXEffect)
  local spellsOfItem = {}
  for _, p in ipairs(itemSpellPairs(itemEffect, itemXEffect)) do
    spellsOfItem[p.item] = spellsOfItem[p.item] or {}
    spellsOfItem[p.item][p.spell] = true
  end
  local questsOfSpell = {}
  for i, row in ipairs(spellEffect) do
    if num("SpellEffect", i, row, "Effect") == G.EFFECT_QUEST_COMPLETE then
      local spell = num("SpellEffect", i, row, "SpellID")
      questsOfSpell[spell] = questsOfSpell[spell] or {}
      questsOfSpell[spell][num("SpellEffect", i, row, "EffectMiscValue", 0)] = true
    end
  end

  local warnings = {}
  for _, s in ipairs(knowledge.sources) do
    if s.itemID and spellsOfItem[s.itemID] then
      local derived = {}
      for spell in pairs(spellsOfItem[s.itemID]) do
        for q in pairs(questsOfSpell[spell] or {}) do derived[q] = true end
      end
      local have, list = {}, {}
      for _, q in ipairs(s.quests) do have[q] = true; list[#list + 1] = tostring(q) end
      local missing = {}
      for q in pairs(derived) do if not have[q] then missing[#missing + 1] = q end end
      table.sort(missing)
      for _, q in ipairs(missing) do
        warnings[#warnings + 1] = string.format("%s: item %d completes quest %d, table has %s",
          s.id, s.itemID, q, table.concat(list, " "))
      end
    end
  end
  return warnings
end

-- One data file in 1a's format. version is "12.1.5"; build is the integer client build or nil.
-- opts.empty uses the --empty header (wago.tools unavailable).
function G.render(name, version, build, tbl, opts)
  if type(name) ~= "string" then error("render: name must be a string", 0) end
  if build ~= nil and (type(build) ~= "number" or build ~= math.floor(build)) then
    error("render: build must be an integer or nil", 0)
  end
  local header
  if opts and opts.empty then
    header = G.EMPTY_HEADER
  else
    header = string.format(G.HEADER, tostring(version) .. (build and ("." .. string.format("%d", build)) or ""))
  end
  local buildText = build and string.format("%d", build) or "nil"
  return header .. "\n"
    .. "local ADDON_NAME, ns = ...\n"
    .. string.format("ns.GameData.Define(%q, %s, %s)", name, buildText, serialize(tbl)) .. "\n"
end

return G
